using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Diff.Tests;

/// <summary>
/// G-214: an identity's sequence is compared only in the options its column states; the database states all it has. Its generation is compared on the
/// column.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class IdentityOptionsDiffTests
{
    private const string Live = "CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5 CACHE 20));";

    [TestMethod]
    [DataRow("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY);")]
    [DataRow("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 10));")]
    [DataRow("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (CACHE 20 INCREMENT 5));")]
    public void AnOptionTheProjectDoesNotStateIsNotCompared(string project)
    {
        var result = new DiffEngine().Diff(Build(Live), Build(project));

        Assert.IsEmpty(result.Modified, Describe(result));
    }

    [TestMethod]
    public void AStatedOptionThatDiffersIsTheChange()
    {
        var change = new DiffEngine().Diff(Build(Live), Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 5));")).Modified.Single();

        Assert.AreEqual("public.t_id_seq", change.NodeId);
        var detail = change.Details.Single();
        Assert.AreEqual(nameof(SequenceDefinition.StartValue), detail.PropertyName);
        Assert.AreEqual("10", detail.OldValue);
        Assert.AreEqual("1", detail.NewValue);
    }

    [TestMethod]
    public void AGenerationChangeIsReportedOnTheColumn()
    {
        var result = new DiffEngine().Diff(Build(Live), Build("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY);"));

        Assert.IsTrue(result.Modified.Any(static change => change.Details.Any(static detail => detail.PropertyName == nameof(ColumnDefinition.IdentityGeneration))), Describe(result));
        Assert.IsFalse(result.Modified.Any(static change => change.NodeId == "public.t_id_seq"), Describe(result));
    }

    private static string Describe(ChangeSet result)
        => string.Join("; ", result.Modified.Select(static change => change.NodeId + " [" + string.Join(", ", change.Details.Select(static detail => $"{detail.PropertyName}: {detail.OldValue} -> {detail.NewValue}")) + "]"));

    private static DatabaseModel Build(string sql) => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
}
