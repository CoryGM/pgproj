using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Diff.Tests;

/// <summary>
/// G-57: the live catalog reports every sequence option, while a project may leave them implicit, so a plain
/// <c>CREATE SEQUENCE</c> and the sequence of an <c>integer</c> identity column re-diffed after publish. Options are now
/// compared with PostgreSQL's defaults applied. Both directions matter: spelling differences report nothing, and a real
/// change is still reported.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class SequenceOptionsDiffTests
{
    private const string BigintMax = "9223372036854775807";

    [TestMethod]
    public void SelfDiffIsEmpty()
    {
        var model = Build("create sequence public.s as integer increment by 2 minvalue 0 maxvalue 90 start with 4 cache 5 cycle;");

        Assert.IsEmpty(new DiffEngine().Execute(model, model).ModifiedSequences);
    }

    /// <summary>The right-hand side is how the live catalog reports the same sequence.</summary>
    [TestMethod]
    [DataRow("", $"as bigint increment by 1 minvalue 1 maxvalue {BigintMax} start with 1 cache 1")]
    [DataRow("as integer", "as integer increment by 1 minvalue 1 maxvalue 2147483647 start with 1 cache 1")]
    [DataRow("as int4", "as integer")]
    [DataRow("as smallint", "as smallint minvalue 1 maxvalue 32767")]
    [DataRow("increment by -1", $"as bigint increment by -1 minvalue -9223372036854775808 maxvalue -1 start with -1 cache 1")]
    [DataRow("as integer increment by -1", "as integer increment by -1 minvalue -2147483648 maxvalue -1 start with -1 cache 1")]
    [DataRow("minvalue 10", "minvalue 10 start with 10")]
    [DataRow("maxvalue 100 increment by -1", $"increment by -1 minvalue -9223372036854775808 maxvalue 100 start with 100")]
    [DataRow("minvalue 0", "minvalue 0 start with 0")]
    [DataRow("cache 1", "")]
    [DataRow("no cycle", "")]
    [DataRow("increment by 1", "")]
    [DataRow("cache 20 cycle", "cache 20 cycle increment by 1")]
    public void SpellingDifferencesProduceNoSequenceChange(string written, string reported)
    {
        var result = new DiffEngine().Execute(Build($"create sequence public.s {reported};"), Build($"create sequence public.s {written};"));

        Assert.IsEmpty(result.ModifiedSequences, $"'{written}' vs '{reported}': " + Describe(result));
    }

    /// <summary>The differences the defaults must never hide, or publish would leave the sequence wrong.</summary>
    [TestMethod]
    [DataRow("", "maxvalue 100", "MaxValue")]
    [DataRow("maxvalue 100", "maxvalue 200", "MaxValue")]
    [DataRow("", "minvalue 0", "MinValue")]
    [DataRow("", "increment by 2", "IncrementBy")]
    [DataRow("", "start with 5", "StartValue")]
    [DataRow("", "cache 10", "CacheSize")]
    [DataRow("", "cycle", "Cycle")]
    [DataRow("cycle", "", "Cycle")]
    [DataRow("as integer", "as smallint", "DataType")]
    [DataRow("", "as integer", "DataType")]
    [DataRow("as integer", "", "MaxValue")]
    [DataRow("increment by 1", "increment by -1", "IncrementBy")]
    [DataRow("increment by 5", "", "IncrementBy")]
    [DataRow("cache 20", "", "CacheSize")]
    public void GenuineOptionChangesAreReported(string oldOptions, string newOptions, string expectedProperty)
    {
        var result = new DiffEngine().Execute(Build($"create sequence public.s {oldOptions};"), Build($"create sequence public.s {newOptions};"));

        Assert.HasCount(1, result.ModifiedSequences, $"'{oldOptions}' vs '{newOptions}': " + Describe(result));
        Assert.IsTrue(
            result.ModifiedSequences[0].Details.Any(detail => detail.PropertyName == expectedProperty),
            $"'{oldOptions}' vs '{newOptions}' expected a {expectedProperty} difference: " + Describe(result));
    }

    [TestMethod]
    public void ReportedChangeShowsTheEffectiveValues()
    {
        var result = new DiffEngine().Execute(Build("create sequence public.s maxvalue 100;"), Build("create sequence public.s;"));

        var detail = result.ModifiedSequences.Single().Details.Single();
        Assert.AreEqual("MaxValue", detail.PropertyName);
        Assert.AreEqual("100", detail.OldValue);
        Assert.AreEqual(BigintMax, detail.NewValue);
    }

    /// <summary>
    /// The project side of a table with an identity column against the exact text a live server produces (an owned sequence
    /// that spells out every option): a published identity column must re-diff empty (this was the integer/bigint MaxValue bug).
    /// </summary>
    [TestMethod]
    [DataRow("integer", "integer", "2147483647")]
    [DataRow("smallint", "smallint", "32767")]
    [DataRow("bigint", "bigint", BigintMax)]
    public void IdentityColumnAgainstItsLiveRenderingDiffsEmpty(string columnType, string liveType, string liveMax)
    {
        var project = Build($"create table public.t (id {columnType} generated by default as identity primary key);");
        var live = Build(
            $"CREATE TABLE \"public\".\"t\" (\n\"id\" {liveType} GENERATED BY DEFAULT AS IDENTITY NOT NULL\n);\n"
            + "ALTER TABLE \"public\".\"t\" ADD CONSTRAINT t_pkey PRIMARY KEY (\"id\");\n"
            + $"CREATE SEQUENCE \"public\".\"t_id_seq\" AS {liveType} INCREMENT BY 1 MINVALUE 1 MAXVALUE {liveMax} START WITH 1 CACHE 1 OWNED BY \"public\".\"t\".\"id\";");

        var result = new DiffEngine().Diff(live, project);

        Assert.AreEqual(0, result.Added.Count + result.Removed.Count + result.Modified.Count, string.Join("; ", result.Modified.Select(static change => change.NodeId + " [" + string.Join(", ", change.Details.Select(static detail => $"{detail.PropertyName}: {detail.OldValue} -> {detail.NewValue}")) + "]")));
    }

    [TestMethod]
    public void IdentityColumnWhoseTypeChangesIsStillReportedOnItsSequence()
    {
        var oldModel = Build("create table public.t (id integer generated by default as identity);");
        var newModel = Build("create table public.t (id bigint generated by default as identity);");

        var result = new DiffEngine().Diff(oldModel, newModel);

        var sequenceChange = result.Modified.Single(static change => change.NodeId == "public.t_id_seq");
        Assert.IsTrue(sequenceChange.Details.Any(static detail => detail.PropertyName == "DataType"), string.Join(", ", sequenceChange.Details.Select(static detail => detail.PropertyName)));

        // Only the options an identity states are compared (G-214); its maximum follows the type, as PostgreSQL moves a default maximum with it.
        Assert.IsFalse(sequenceChange.Details.Any(static detail => detail.PropertyName == "MaxValue"));
    }

    private static string Describe(DiffResult result)
        => string.Join("; ", result.ModifiedSequences.Select(static change => change.NodeId + " [" + string.Join(", ", change.Details.Select(static detail => $"{detail.PropertyName}: {detail.OldValue} -> {detail.NewValue}")) + "]"));

    private static DatabaseModel Build(string sql)
        => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
}
