using PgProj.Dependencies;
using PgProj.Diff;
using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Deploy.Tests;

/// <summary>
/// G-58: a serial column's sequence was created <c>OWNED BY</c> a table that did not exist yet (<c>42P01</c>), so
/// <c>serial</c> never deployed to a real server. The sequence must be created first (the table's default needs it),
/// without ownership, and handed to its column after the table exists.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class SerialSequenceDeployTests
{
    [TestMethod]
    public void SerialSequenceIsCreatedFirstWithoutOwnershipAndOwnedAfterTheTable()
    {
        var statements = Statements(DatabaseModel.Empty, BuildModel("create schema s; create table s.t (id serial primary key, name text);"));

        var createSequence = IndexOf(statements, "CREATE SEQUENCE \"s\".\"t_id_seq\"");
        var createTable = IndexOf(statements, "CREATE TABLE \"s\".\"t\"");
        var owned = IndexOf(statements, "ALTER SEQUENCE \"s\".\"t_id_seq\" OWNED BY \"s\".\"t\".\"id\";");

        Assert.IsLessThan(createTable, createSequence, string.Join("\n", statements));
        Assert.IsLessThan(owned, createTable, string.Join("\n", statements));
        Assert.IsFalse(statements[createSequence].Contains("OWNED BY", StringComparison.Ordinal), statements[createSequence]);
    }

    [TestMethod]
    public void SerialDefaultIsSchemaQualified()
    {
        var script = Script(DatabaseModel.Empty, BuildModel("create schema s; create table s.t (id serial primary key);"));

        StringAssert.Contains(script, "DEFAULT nextval('s.t_id_seq'::regclass)", script);
    }

    [TestMethod]
    public void EveryOwnedSequenceIsHandedToItsColumnAfterAllTablesExist()
    {
        var statements = Statements(
            DatabaseModel.Empty,
            BuildModel("create table public.a (id serial primary key); create table public.b (id bigserial primary key, n smallserial);"));

        var lastCreateTable = statements.Select((statement, index) => (statement, index)).Where(static entry => entry.statement.StartsWith("CREATE TABLE", StringComparison.Ordinal)).Max(static entry => entry.index);
        var owners = statements.Select((statement, index) => (statement, index)).Where(static entry => entry.statement.StartsWith("ALTER SEQUENCE", StringComparison.Ordinal)).ToArray();

        Assert.HasCount(3, owners, string.Join("\n", statements));
        Assert.IsTrue(owners.All(entry => entry.index > lastCreateTable), string.Join("\n", statements));
    }

    [TestMethod]
    public void ExplicitSequenceOwnedByAnExistingColumnIsCreatedThenOwned()
    {
        var oldModel = BuildModel("create table public.t (id bigint primary key);");
        var newModel = BuildModel("create table public.t (id bigint primary key); create sequence public.t_id_seq owned by public.t.id;");

        var statements = Statements(oldModel, newModel);

        Assert.HasCount(2, statements, string.Join("\n", statements));
        Assert.IsFalse(statements[0].Contains("OWNED BY", StringComparison.Ordinal), statements[0]);
        Assert.AreEqual("ALTER SEQUENCE \"public\".\"t_id_seq\" OWNED BY \"public\".\"t\".\"id\";", statements[1]);
    }

    [TestMethod]
    public void IdentityColumnGetsNoSequenceStatements()
    {
        var statements = Statements(DatabaseModel.Empty, BuildModel("create table public.t (id integer generated by default as identity primary key);"));

        Assert.IsFalse(statements.Any(static statement => statement.StartsWith("ALTER SEQUENCE", StringComparison.Ordinal) || statement.StartsWith("CREATE SEQUENCE", StringComparison.Ordinal)), string.Join("\n", statements));
    }

    [TestMethod]
    public void UnownedSequenceIsCreatedAsBefore()
    {
        var statements = Statements(DatabaseModel.Empty, BuildModel("create sequence public.plain_seq;"));

        Assert.HasCount(1, statements);
        StringAssert.StartsWith(statements[0], "CREATE SEQUENCE \"public\".\"plain_seq\"");
    }

    [TestMethod]
    public void OwnershipStatementQuotesEveryPart()
    {
        var sequence = BuildModel("create sequence \"My Schema\".\"Seq\";").Sequences.Values.Single() with
        {
            OwnedByTable = "My Schema.Orders",
            OwnedByColumn = "Order Id",
        };

        var sql = new SequenceOwnershipOperation { NodeId = sequence.Key, NodeKind = ChangeNodeKind.Sequence, Sequence = sequence }.GenerateSql();

        Assert.AreEqual("ALTER SEQUENCE \"My Schema\".\"Seq\" OWNED BY \"My Schema\".\"Orders\".\"Order Id\";", sql);
    }

    [TestMethod]
    public void DroppingATableWithASerialColumnDropsItsSequenceOnlyIfItStillExists()
    {
        var oldModel = BuildModel("create table public.t (id serial primary key);");

        var statements = Statements(oldModel, DatabaseModel.Empty);

        Assert.IsTrue(statements.Any(static statement => statement == "DROP SEQUENCE IF EXISTS \"public\".\"t_id_seq\";"), string.Join("\n", statements));
        var dropTable = IndexOf(statements, "DROP TABLE");
        var dropSequence = IndexOf(statements, "DROP SEQUENCE IF EXISTS");
        Assert.IsLessThan(dropSequence, dropTable, "The table must be dropped before its sequence. " + string.Join("\n", statements));
    }

    private static int IndexOf(IReadOnlyList<string> statements, string prefix)
    {
        for (var index = 0; index < statements.Count; index++)
        {
            if (statements[index].StartsWith(prefix, StringComparison.Ordinal))
            {
                return index;
            }
        }

        Assert.Fail($"No statement starts with '{prefix}'. Statements:\n{string.Join("\n", statements)}");
        return -1;
    }

    private static IReadOnlyList<string> Statements(DatabaseModel oldModel, DatabaseModel newModel)
    {
        var generator = new ScriptGenerator();
        var batch = generator.Generate(new DiffEngine().Diff(oldModel, newModel), new DependencyAnalyzer().Analyze(oldModel, newModel));
        return batch.Operations
            .Where(static operation => operation is not SchemaCreateOperation)
            .Select(static operation => operation.GenerateSql().Trim())
            .ToArray();
    }

    private static string Script(DatabaseModel oldModel, DatabaseModel newModel)
    {
        var generator = new ScriptGenerator();
        return generator.GenerateSqlScript(generator.Generate(new DiffEngine().Diff(oldModel, newModel), new DependencyAnalyzer().Analyze(oldModel, newModel)));
    }

    private static DatabaseModel BuildModel(string sql)
        => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
}
