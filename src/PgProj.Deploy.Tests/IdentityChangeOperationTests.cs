using PgProj.Dependencies;
using PgProj.Diff;
using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Deploy.Tests;

/// <summary>
/// G-214: an identity column's options are deployed as written, and a change to one is made in place: its generation (<c>SET GENERATED</c>), identity
/// added (<c>ADD GENERATED</c>, then the sequence moved past the column's values) or dropped (<c>DROP IDENTITY</c>, before <c>DROP NOT NULL</c>), and a
/// stated option (<c>SET ...</c>). A changed <c>START WITH</c> is recorded, never a restart of the counter.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class IdentityChangeOperationTests
{
    [TestMethod]
    public void IdentityOptionsAreCreatedAsWritten()
    {
        var script = ScriptFor(DatabaseModel.Empty, Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY ( start with 10  INCREMENT 5 ) PRIMARY KEY);"));

        StringAssert.Contains(script, "GENERATED BY DEFAULT AS IDENTITY (start with 10  INCREMENT 5)", script);
    }

    [TestMethod]
    [DataRow("ALWAYS", "BY DEFAULT")]
    [DataRow("BY DEFAULT", "ALWAYS")]
    public void TheGenerationIsChangedInPlace(string before, string after)
    {
        var script = ScriptFor(
            Build($"CREATE TABLE public.t (id int GENERATED {before} AS IDENTITY);"),
            Build($"CREATE TABLE public.t (id int GENERATED {after} AS IDENTITY);"));

        StringAssert.Contains(script, $"ALTER TABLE \"public\".\"t\" ALTER COLUMN \"id\" SET GENERATED {after};", script);
        Assert.IsFalse(script.Contains("DROP", StringComparison.Ordinal), script);
    }

    [TestMethod]
    public void IdentityAddedToAColumnIsMovedPastItsValues()
    {
        var script = ScriptFor(Build("CREATE TABLE public.t (id int);"), Build("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY);"));

        var notNull = script.IndexOf("ALTER COLUMN \"id\" SET NOT NULL;", StringComparison.Ordinal);
        var add = script.IndexOf("ALTER COLUMN \"id\" ADD GENERATED ALWAYS AS IDENTITY;", StringComparison.Ordinal);
        var setval = script.IndexOf("SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('\"public\".\"t\"', 'id'), max(\"id\")) FROM \"public\".\"t\" HAVING max(\"id\") IS NOT NULL;", StringComparison.Ordinal);
        Assert.IsTrue(notNull >= 0 && notNull < add && add < setval, script);
        Assert.IsFalse(script.Split('\n').Any(static line => line.StartsWith("CREATE SEQUENCE", StringComparison.Ordinal)), script);
    }

    [TestMethod]
    [DataRow("START WITH 100")]
    [DataRow("INCREMENT BY -1")]
    public void AStatedStartOrADescendingIdentityIsNotMoved(string options)
    {
        var script = ScriptFor(Build("CREATE TABLE public.t (id int NOT NULL);"), Build($"CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY ({options}));"));

        StringAssert.Contains(script, $"ADD GENERATED ALWAYS AS IDENTITY ({options});", script);
        Assert.IsFalse(script.Contains("setval", StringComparison.Ordinal), script);
    }

    [TestMethod]
    public void IdentityIsDroppedBeforeTheColumnAllowsNulls()
    {
        var script = ScriptFor(Build("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY);"), Build("CREATE TABLE public.t (id int);"));

        var drop = script.IndexOf("ALTER TABLE \"public\".\"t\" ALTER COLUMN \"id\" DROP IDENTITY;", StringComparison.Ordinal);
        var nullable = script.IndexOf("ALTER COLUMN \"id\" DROP NOT NULL;", StringComparison.Ordinal);
        Assert.IsTrue(drop >= 0 && drop < nullable, script);
        Assert.IsFalse(script.Split('\n').Any(static line => line.StartsWith("DROP SEQUENCE", StringComparison.Ordinal)), script);
    }

    [TestMethod]
    public void DroppingIdentityIsNotDestructive()
    {
        var batch = Generate(Build("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY);"), Build("CREATE TABLE public.t (id int NOT NULL);"));

        Assert.IsEmpty(batch.GetDestructiveOperations());
    }

    [TestMethod]
    public void AChangedOptionIsSetThroughTheColumnAndAChangedStartNeverRestarts()
    {
        var script = ScriptFor(
            Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 10));"),
            Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 20 INCREMENT BY 5));"));

        StringAssert.Contains(script, "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"id\" SET INCREMENT BY 5 SET START WITH 20;", script);
        Assert.IsFalse(script.Contains("RESTART", StringComparison.Ordinal), script);
        Assert.IsFalse(script.Contains("ALTER SEQUENCE", StringComparison.Ordinal), script);
    }

    /// <summary>The database states every option it has; one the project leaves out is PostgreSQL's choice and is not changed.</summary>
    [TestMethod]
    public void AnOptionTheProjectDoesNotStateIsLeftAlone()
    {
        var script = ScriptFor(
            Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 10 CACHE 20));"),
            Build("CREATE TABLE public.t (id int GENERATED BY DEFAULT AS IDENTITY);"));

        Assert.IsFalse(script.Contains("ALTER", StringComparison.Ordinal), script);
    }

    private static OperationBatch Generate(DatabaseModel oldModel, DatabaseModel newModel)
        => new ScriptGenerator().Generate(new DiffEngine().Diff(oldModel, newModel), new DependencyAnalyzer().Analyze(oldModel, newModel));

    private static string ScriptFor(DatabaseModel oldModel, DatabaseModel newModel)
        => new ScriptGenerator().GenerateSqlScript(Generate(oldModel, newModel));

    private static DatabaseModel Build(string sql) => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
}
