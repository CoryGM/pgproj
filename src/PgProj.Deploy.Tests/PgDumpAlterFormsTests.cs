using PgProj.Dependencies;
using PgProj.Diff;
using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Deploy.Tests;

/// <summary>
/// G-236: <c>pg_dump</c> writes a partition, a serial column's default, an identity, a column's storage and compression, and a sequence's owner as <c>ALTER</c> statements. They are folded
/// into the model as if <c>CREATE TABLE</c> or <c>CREATE SEQUENCE</c> had said them, so a project built from a dump keeps them instead of warning and ignoring them.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class PgDumpAlterFormsTests
{
    [TestMethod]
    public void AttachPartitionMakesTheTableAPartitionWithItsBound()
    {
        var script = Script("""
            CREATE TABLE public.parted (a integer NOT NULL, b text) PARTITION BY RANGE (a);
            CREATE TABLE public.parted_1 (a integer NOT NULL, b text);
            CREATE TABLE public.parted_d (a integer NOT NULL, b text);
            ALTER TABLE ONLY public.parted ATTACH PARTITION public.parted_1 FOR VALUES FROM (1) TO (10);
            ALTER TABLE ONLY public.parted ATTACH PARTITION public.parted_d DEFAULT;
            """);

        StringAssert.Contains(script, "CREATE TABLE \"public\".\"parted_1\" PARTITION OF \"public\".\"parted\" FOR VALUES FROM (1) TO (10);");
        StringAssert.Contains(script, "CREATE TABLE \"public\".\"parted_d\" PARTITION OF \"public\".\"parted\" DEFAULT;");
    }

    [TestMethod]
    public void AttachPartitionInAnotherFileThanTheTablesIsFound()
    {
        var model = new SemanticPipeline().Execute([
            new PgQueryParser().Parse("ALTER TABLE ONLY public.parted ATTACH PARTITION public.parted_1 FOR VALUES FROM (1) TO (10);"),
            new PgQueryParser().Parse("CREATE TABLE public.parted (a integer NOT NULL) PARTITION BY RANGE (a); CREATE TABLE public.parted_1 (a integer NOT NULL);")]);

        Assert.AreEqual("parted", model.Tables["public.parted_1"].PartitionOfTableName);
        Assert.IsFalse(model.Diagnostics.Any(static d => d.Severity == SemanticDiagnosticSeverity.Error), string.Join("; ", model.Diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    public void ASerialColumnsDefaultAndTheSequencesOwnerAreKept()
    {
        var script = Script("""
            CREATE SEQUENCE public.s AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
            CREATE TABLE public.t (id integer NOT NULL, name text);
            ALTER TABLE ONLY public.t ALTER COLUMN id SET DEFAULT nextval('public.s'::regclass);
            ALTER SEQUENCE public.s OWNED BY public.t.id;
            """);

        StringAssert.Contains(script, "\"id\" integer NOT NULL DEFAULT nextval('public.s'::regclass)");
        StringAssert.Contains(script, "ALTER SEQUENCE \"public\".\"s\" OWNED BY \"public\".\"t\".\"id\";");
    }

    [TestMethod]
    public void DropDefaultClearsTheDefault()
    {
        var script = Script("""
            CREATE TABLE public.t (id integer DEFAULT 5, name text);
            ALTER TABLE public.t ALTER COLUMN id DROP DEFAULT;
            """);

        Assert.IsFalse(script.Contains("DEFAULT", StringComparison.Ordinal), script);
    }

    [TestMethod]
    public void AddGeneratedMakesTheColumnAnIdentityWithItsOptions()
    {
        var script = Script("""
            CREATE TABLE public.i (id integer NOT NULL);
            ALTER TABLE public.i ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.i_id_seq START WITH 5 INCREMENT BY 2 NO MINVALUE NO MAXVALUE CACHE 1);
            """);

        StringAssert.Contains(script, "GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.i_id_seq START WITH 5 INCREMENT BY 2 NO MINVALUE NO MAXVALUE CACHE 1)");
    }

    [TestMethod]
    public void StorageAndCompressionAreSetOnTheColumn()
    {
        var script = Script("""
            CREATE TABLE public.t (name text);
            ALTER TABLE ONLY public.t ALTER COLUMN name SET STORAGE EXTERNAL;
            ALTER TABLE ONLY public.t ALTER COLUMN name SET COMPRESSION lz4;
            """);

        // The storage is deployed as the project set it, with ALTER TABLE (G-269); every supported version accepts that form.
        StringAssert.Contains(script, "\"name\" text COMPRESSION lz4");
        StringAssert.Contains(script, "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"name\" SET STORAGE external;");
    }

    [TestMethod]
    public void APartitionsOwnIndexAndKeyAttachedToTheParentsAreTheParentsAndNotCreatedTwice()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("""
            CREATE TABLE public.pt (a integer NOT NULL, b integer) PARTITION BY RANGE (a);
            CREATE TABLE public.pt_1 (a integer NOT NULL, b integer);
            ALTER TABLE ONLY public.pt ATTACH PARTITION public.pt_1 FOR VALUES FROM (0) TO (10);
            ALTER TABLE ONLY public.pt ADD CONSTRAINT pt_pkey PRIMARY KEY (a);
            ALTER TABLE ONLY public.pt_1 ADD CONSTRAINT pt_1_pkey PRIMARY KEY (a);
            CREATE INDEX pt_b_idx ON ONLY public.pt USING btree (b);
            CREATE INDEX pt_1_b_idx ON public.pt_1 USING btree (b);
            ALTER INDEX public.pt_pkey ATTACH PARTITION public.pt_1_pkey;
            ALTER INDEX public.pt_b_idx ATTACH PARTITION public.pt_1_b_idx;
            """)]);

        Assert.IsTrue(model.Indexes.ContainsKey("public.pt_b_idx"), string.Join(", ", model.Indexes.Keys));
        Assert.IsFalse(model.Indexes.Keys.Any(static key => key.EndsWith("pt_1_b_idx", StringComparison.Ordinal)), string.Join(", ", model.Indexes.Keys));
        Assert.IsFalse(model.Constraints.Keys.Any(static key => key.EndsWith("pt_1_pkey", StringComparison.Ordinal)), string.Join(", ", model.Constraints.Keys));
        Assert.IsTrue(model.Constraints.Keys.Any(static key => key.EndsWith("pt_pkey", StringComparison.Ordinal)), string.Join(", ", model.Constraints.Keys));
    }

    [TestMethod]
    public void AnIndexOfATableThatIsNoPartitionIsNotDropped()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("""
            CREATE TABLE public.pt (b integer);
            CREATE TABLE public.other (b integer);
            CREATE INDEX pt_idx ON public.pt USING btree (b);
            CREATE INDEX other_idx ON public.other USING btree (b);
            ALTER INDEX public.pt_idx ATTACH PARTITION public.other_idx;
            """)]);

        Assert.IsTrue(model.Indexes.Keys.Any(static key => key.EndsWith("other_idx", StringComparison.Ordinal)), string.Join(", ", model.Indexes.Keys));
    }

    [TestMethod]
    public void AFormForATableTheProjectDoesNotDeclareIsAWarning()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("ALTER TABLE ONLY public.nope ALTER COLUMN a SET DEFAULT 1; ALTER TABLE ONLY public.nope ATTACH PARTITION public.gone FOR VALUES IN (1);")]);

        Assert.IsGreaterThanOrEqualTo(2, model.Diagnostics.Count(static d => d.Message.Contains("does not declare", StringComparison.Ordinal)), string.Join("; ", model.Diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    public void AnAlterSequenceWithAnotherOptionIsStillNotModeled()
    {
        var tree = new PgQueryParser().Parse("ALTER SEQUENCE public.s RESTART WITH 10;");

        Assert.IsTrue(tree.Diagnostics.Any(static d => d.Message.StartsWith("ALTER SEQUENCE is not modeled", StringComparison.Ordinal)), string.Join("; ", tree.Diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    public void AViewCreatedAsAPlaceholderAndThenReplacedIsTheReplacement()
    {
        var script = Script("""
            CREATE TABLE public.t (a integer);
            CREATE VIEW public.v AS SELECT NULL::integer AS a;
            CREATE OR REPLACE VIEW public.v AS SELECT a FROM public.t;
            """);

        StringAssert.Contains(script, "SELECT a FROM public.t");
        Assert.IsFalse(script.Contains("NULL::integer", StringComparison.Ordinal), script);
    }

    [TestMethod]
    public void TwoPlainViewsOfOneNameAreStillADuplicate()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("CREATE VIEW public.v AS SELECT 1 AS a; CREATE VIEW public.v AS SELECT 2 AS a;")]);

        Assert.IsTrue(model.Diagnostics.Any(static d => d.Message.StartsWith("Duplicate View definition", StringComparison.Ordinal)), string.Join("; ", model.Diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    public void APartitionsCopyOfAnAncestorsCheckIsNotAddedASecondTime()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("""
            CREATE TABLE public.pt (a integer NOT NULL, CONSTRAINT pt_a_check CHECK ((a > 0))) PARTITION BY RANGE (a);
            CREATE TABLE public.pt_1 (a integer NOT NULL, CONSTRAINT pt_a_check CHECK ((a > 0)), CONSTRAINT own_check CHECK ((a < 100)));
            ALTER TABLE ONLY public.pt ATTACH PARTITION public.pt_1 FOR VALUES FROM (1) TO (10);
            """)]);

        Assert.IsFalse(model.Constraints.ContainsKey("public.pt_1.pt_a_check"), string.Join(", ", model.Constraints.Keys));
        Assert.IsTrue(model.Constraints.ContainsKey("public.pt_1.own_check"), string.Join(", ", model.Constraints.Keys));
        Assert.IsTrue(model.Constraints.ContainsKey("public.pt.pt_a_check"), string.Join(", ", model.Constraints.Keys));
    }

    private static string Script(string sql)
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
        var batch = new ScriptGenerator().Generate(new DiffEngine().Diff(DatabaseModel.Empty, model), new DependencyAnalyzer().Analyze(DatabaseModel.Empty, model));
        return string.Join("\n", batch.Operations.Where(static operation => operation is not SchemaCreateOperation).Select(static operation => operation.GenerateSql().Replace("\r\n", "\n", StringComparison.Ordinal))).Trim();
    }
}
