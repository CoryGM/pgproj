using PgProj.Diff;
using PgProj.Semantics;

namespace PgProj.Deploy.Tests;

[TestClass]
public sealed class IdentityColumnOperationTests
{
    [TestMethod]
    public void CreateTableEmitsGeneratedAlwaysAsIdentity()
    {
        var table = CreateTable("public.orders", "orders", "public",
            [CreateColumn("id", "public.orders.id", "integer", identityGeneration: "ALWAYS")]);

        var operation = new CreateOperation
        {
            NodeId = table.Key,
            NodeKind = ChangeNodeKind.Table,
            Node = table,
        };

        var sql = operation.GenerateSql();

        StringAssert.Contains(sql, "\"id\" integer GENERATED ALWAYS AS IDENTITY");
    }

    [TestMethod]
    public void CreateTableEmitsGeneratedByDefaultAsIdentity()
    {
        var table = CreateTable("public.orders", "orders", "public",
            [CreateColumn("id", "public.orders.id", "integer", identityGeneration: "BY DEFAULT")]);

        var operation = new CreateOperation
        {
            NodeId = table.Key,
            NodeKind = ChangeNodeKind.Table,
            Node = table,
        };

        var sql = operation.GenerateSql();

        StringAssert.Contains(sql, "\"id\" integer GENERATED BY DEFAULT AS IDENTITY");
    }

    [TestMethod]
    public void CreateTableWithNoIdentityColumnEmitsPlainColumnType()
    {
        var table = CreateTable("public.orders", "orders", "public",
            [CreateColumn("name", "public.orders.name", "text", identityGeneration: null)]);

        var operation = new CreateOperation
        {
            NodeId = table.Key,
            NodeKind = ChangeNodeKind.Table,
            Node = table,
        };

        var sql = operation.GenerateSql();

        StringAssert.Contains(sql, "\"name\" text");
        Assert.IsFalse(sql.Contains("IDENTITY"), "Non-identity column must not emit IDENTITY.");
    }

    private static TableDefinition CreateTable(string key, string name, string? schemaName, IReadOnlyList<ColumnDefinition> columns)
        => new(key, name, schemaName, columns, [], [], [], [], [], [], [], [], []);

    private static ColumnDefinition CreateColumn(string name, string key, string dataType, string? identityGeneration = null)
        => new(key, name, null, null, dataType, dataType, true, null, false, null, null, null,
            [], [], [], [], [], [], [], [],
            identityGeneration);
}
