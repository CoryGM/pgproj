namespace PgProj.Parser.Tests;

[TestClass]
public sealed class IdentityColumnParsingTests
{
    [TestMethod]
    public void GeneratedAlwaysAsIdentityIsParsed()
    {
        var tree = new PgQueryParser().Parse(
            "CREATE TABLE public.orders (id integer GENERATED ALWAYS AS IDENTITY);");

        var table = tree.Nodes.OfType<TableNode>().Single();
        var column = table.Columns.Single(c => c.Name == "id");

        Assert.AreEqual("ALWAYS", column.IdentityGeneration);
    }

    [TestMethod]
    public void GeneratedByDefaultAsIdentityIsParsed()
    {
        var tree = new PgQueryParser().Parse(
            "CREATE TABLE public.orders (id integer GENERATED BY DEFAULT AS IDENTITY);");

        var table = tree.Nodes.OfType<TableNode>().Single();
        var column = table.Columns.Single(c => c.Name == "id");

        Assert.AreEqual("BY DEFAULT", column.IdentityGeneration);
    }

    [TestMethod]
    public void NonIdentityColumnHasNullIdentityGeneration()
    {
        var tree = new PgQueryParser().Parse(
            "CREATE TABLE public.orders (id integer, name text);");

        var table = tree.Nodes.OfType<TableNode>().Single();
        foreach (var column in table.Columns)
        {
            Assert.IsNull(column.IdentityGeneration, $"Column '{column.Name}' should not have IdentityGeneration set.");
        }
    }

    [TestMethod]
    public void MultipleIdentityColumnsAreParsedIndependently()
    {
        var tree = new PgQueryParser().Parse(
            """
            CREATE TABLE public.t (
                id  integer GENERATED ALWAYS AS IDENTITY,
                alt integer GENERATED BY DEFAULT AS IDENTITY
            );
            """);

        var table = tree.Nodes.OfType<TableNode>().Single();
        var id = table.Columns.Single(c => c.Name == "id");
        var alt = table.Columns.Single(c => c.Name == "alt");

        Assert.AreEqual("ALWAYS", id.IdentityGeneration);
        Assert.AreEqual("BY DEFAULT", alt.IdentityGeneration);
    }
}
