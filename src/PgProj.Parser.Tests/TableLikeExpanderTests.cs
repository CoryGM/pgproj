namespace PgProj.Parser.Tests;

/// <summary>
/// G-221: a table written with <c>LIKE</c> is given what PostgreSQL copies, as the options say, each copy marked with its source; a key, exclusion
/// constraint, index, or statistics object is named as PostgreSQL names it (each name below is what PostgreSQL 16 and 18 gave the same statements), and a
/// <c>CHECK</c> keeps its source's name.
/// </summary>
[TestClass]
public sealed class TableLikeExpanderTests
{
    private const string Source = """
        CREATE TABLE public.a (id int PRIMARY KEY, n text DEFAULT 'x' NOT NULL, c text COLLATE "C", g int GENERATED ALWAYS AS (id * 2) STORED,
            ident int GENERATED BY DEFAULT AS IDENTITY (START 5), u int, v int, CHECK (id > 0), CONSTRAINT named_ck CHECK (u > 0),
            UNIQUE (u) INCLUDE (v), EXCLUDE USING btree (v WITH =));
        CREATE INDEX a_lower ON public.a (lower(n));
        CREATE INDEX a_uu ON public.a (u, u);
        CREATE UNIQUE INDEX a_v ON public.a (v) WHERE v > 1;
        CREATE INDEX a_named ON public.a (n);
        CREATE STATISTICS public.a_st ON u, v FROM public.a;
        COMMENT ON COLUMN public.a.n IS 'n comment';
        COMMENT ON CONSTRAINT a_id_check ON public.a IS 'ck comment';
        COMMENT ON INDEX public.a_named IS 'idx comment';
        """;

    [TestMethod]
    public void TheColumnsAreCopiedWhereTheClauseIs()
    {
        var (tree, _) = Expand(Source + "CREATE TABLE public.b (x int, LIKE public.a INCLUDING ALL, extra int);");

        var table = TableNamed(tree, "b");
        CollectionAssert.AreEqual(new[] { "x", "id", "n", "c", "g", "ident", "u", "v", "extra" }, table.Columns.Select(static column => column.Name).ToArray());
        CollectionAssert.AreEqual(new string?[] { null, "public.a", "public.a", "public.a", "public.a", "public.a", "public.a", "public.a", null }, table.Columns.Select(static column => column.CopiedByLike).ToArray());
        Assert.IsTrue(table.Columns.All(static column => column.TableName == "b"));
    }

    [TestMethod]
    public void IncludingAllCopiesDefaultsGeneratedIdentityAndCollation()
    {
        var columns = TableNamed(Expand(Source + "CREATE TABLE public.b (LIKE public.a INCLUDING ALL);").Tree, "b").Columns.ToDictionary(static column => column.Name!);

        Assert.AreEqual("'x'", columns["n"].RawDefaultExpression);
        Assert.IsTrue(columns["g"].IsGenerated);
        Assert.AreEqual("BY DEFAULT", columns["ident"].IdentityGeneration);
        Assert.AreEqual("START 5", columns["ident"].IdentityOptionsText);
        Assert.AreEqual("C", columns["c"].CollationName);
        // NOT NULL is copied, a key's included.
        Assert.IsFalse(columns["id"].IsNullable);
        Assert.IsFalse(columns["n"].IsNullable);
    }

    [TestMethod]
    public void WithoutOptionsOnlyColumnsTheirNotNullAndCollationAreCopied()
    {
        var (tree, _) = Expand(Source + "CREATE TABLE public.c (LIKE public.a);");

        var columns = TableNamed(tree, "c").Columns.ToDictionary(static column => column.Name!);
        Assert.IsNull(columns["n"].RawDefaultExpression);
        Assert.IsFalse(columns["g"].IsGenerated);
        Assert.IsNull(columns["ident"].IdentityGeneration);
        Assert.IsFalse(columns["ident"].IsNullable);
        Assert.IsFalse(columns["id"].IsNullable);
        Assert.AreEqual("C", columns["c"].CollationName);
        Assert.IsFalse(tree.Nodes.OfType<ConstraintNode>().Any(static constraint => constraint.TableName == "c"));
        Assert.IsFalse(tree.Nodes.OfType<IndexNode>().Any(static index => index.TableName == "c"));
    }

    [TestMethod]
    public void ConstraintsCopyTheChecksUnderTheirSourcesNames()
    {
        var (tree, _) = Expand(Source + "CREATE TABLE public.d (LIKE public.a INCLUDING CONSTRAINTS);");

        var checks = tree.Nodes.OfType<ConstraintNode>().Where(static constraint => constraint.TableName == "d").ToArray();
        CollectionAssert.AreEquivalent(new[] { "a_id_check", "named_ck" }, checks.Select(static constraint => constraint.Name).ToArray());
        Assert.IsTrue(checks.All(static constraint => constraint.CopiedByLike == "public.a" && !constraint.IsNameGenerated));
    }

    [TestMethod]
    public void IndexesAreNamedAsPostgreSqlNamesThem()
    {
        var (tree, _) = Expand(Source + "CREATE TABLE public.b (LIKE public.a INCLUDING INDEXES);");

        var names = tree.Nodes.OfType<ConstraintNode>().Where(static constraint => constraint.TableName == "b").Select(static constraint => constraint.Name)
            .Concat(tree.Nodes.OfType<IndexNode>().Where(static index => index.TableName == "b").Select(static index => index.Name))
            .ToArray();
        CollectionAssert.AreEquivalent(new[] { "b_pkey", "b_u_v_key", "b_v_excl", "b_lower_idx", "b_u_u1_idx", "b_v_idx", "b_n_idx" }, names);
        Assert.AreEqual("v > 1", tree.Nodes.OfType<IndexNode>().Single(static index => index.Name == "b_v_idx").RawPredicateExpression);
    }

    [TestMethod]
    public void AnExpressionIndexIsNamedFromItsExpressions()
    {
        var (tree, _) = Expand("""
            CREATE TABLE public.e (id int, t text);
            CREATE INDEX e_x ON public.e ((t::int), (id + 1), (t COLLATE "C"), coalesce(t, 'x'), (CASE WHEN id > 0 THEN t END), (lower(t)::varchar));
            CREATE TABLE public.f (LIKE public.e INCLUDING INDEXES);
            """);

        Assert.AreEqual("f_t_expr_t1_coalesce_case_lower_idx", tree.Nodes.OfType<IndexNode>().Single(static index => index.TableName == "f").Name);
    }

    [TestMethod]
    public void StatisticsListColumnsFirstAndAreNamedForTheTable()
    {
        var (tree, _) = Expand("""
            CREATE TABLE public.e (id int, t text);
            CREATE STATISTICS public.e_st ON (id + 1), t FROM public.e;
            CREATE TABLE public.f (LIKE public.e INCLUDING STATISTICS);
            """);

        var statistics = tree.Nodes.OfType<StatisticsNode>().Single(static node => node.TableName == "f");
        Assert.AreEqual("f_t_expr_stat", statistics.Name);
        Assert.AreEqual("t", statistics.Elements[0].Name);
        Assert.IsNotNull(statistics.Elements[1].RawExpression);
    }

    [TestMethod]
    public void ANameTakenInTheSchemaGetsANumber()
    {
        var (tree, _) = Expand("CREATE TABLE public.a (id int PRIMARY KEY); CREATE TABLE public.other (x int); CREATE INDEX b_pkey ON public.other (x); CREATE TABLE public.b (LIKE public.a INCLUDING INDEXES);");

        Assert.AreEqual("b_pkey1", tree.Nodes.OfType<ConstraintNode>().Single(static constraint => constraint.TableName == "b").Name);
    }

    [TestMethod]
    public void CommentsAreCopiedOntoTheCopies()
    {
        var (tree, _) = Expand(Source + "CREATE TABLE public.b (LIKE public.a INCLUDING ALL);");

        var comments = tree.Nodes.OfType<ObjectCommentNode>().Where(static comment => comment.TableName is "b" or "b_n_idx").ToArray();
        Assert.AreEqual("n comment", comments.Single(static comment => comment.ObjectKind == "Column").CommentText);
        Assert.AreEqual("ck comment", comments.Single(static comment => comment.ObjectKind == "Constraint" && comment.ObjectName == "a_id_check").CommentText);
        Assert.AreEqual("idx comment", comments.Single(static comment => comment.ObjectKind == "Index").CommentText);
    }

    [TestMethod]
    public void ATableCopiedFromATableThatCopiesGetsAllOfIt()
    {
        var (tree, _) = Expand("CREATE TABLE public.f (LIKE public.b); CREATE TABLE public.b (LIKE public.a, extra int); CREATE TABLE public.a (id int, n text);");

        CollectionAssert.AreEqual(new[] { "id", "n", "extra" }, TableNamed(tree, "f").Columns.Select(static column => column.Name).ToArray());
        CollectionAssert.AreEqual(new[] { "public.b", "public.b", "public.b" }, TableNamed(tree, "f").Columns.Select(static column => column.CopiedByLike).ToArray());
    }

    [TestMethod]
    public void AColumnTheSourceGetsFromAlterTableIsCopied()
    {
        var (tree, _) = Expand("CREATE TABLE public.a (id int); CREATE TABLE public.b (LIKE public.a); ALTER TABLE public.a ADD COLUMN later text;");

        CollectionAssert.AreEqual(new[] { "id", "later" }, TableNamed(tree, "b").Columns.Select(static column => column.Name).ToArray());
    }

    [TestMethod]
    public void ACompositeTypesFieldsAreCopied()
    {
        var (tree, _) = Expand("CREATE TYPE public.ct AS (p int, q varchar(10)); CREATE TABLE public.e (LIKE public.ct, r int);");

        var table = TableNamed(tree, "e");
        CollectionAssert.AreEqual(new[] { "p", "q", "r" }, table.Columns.Select(static column => column.Name).ToArray());
        Assert.AreEqual("varchar(10)", table.Columns[1].WrittenType);
        Assert.AreEqual(TableLikeNode.TypeSource, table.LikeClauses.Single().SourceKind);
    }

    [TestMethod]
    public void ASourceTheProjectDoesNotDeclareIsListedAndAddsNothing()
    {
        var (tree, external) = Expand("CREATE TABLE app.b (LIKE ext.src INCLUDING ALL, extra int);");

        CollectionAssert.AreEqual(new[] { "ext.src" }, external.ToArray());
        CollectionAssert.AreEqual(new[] { "extra" }, TableNamed(tree, "b").Columns.Select(static column => column.Name).ToArray());
    }

    [TestMethod]
    public void ASourceReadFromTheDatabaseIsCopied()
    {
        var parser = new PgQueryParser();
        var source = parser.Parse("CREATE TABLE ext.src (id integer NOT NULL, n text DEFAULT 'q'::text); ALTER TABLE ext.src ADD CONSTRAINT src_pkey PRIMARY KEY (id);");
        var (trees, external) = TableLikeExpander.Apply([parser.Parse("CREATE TABLE app.b (LIKE ext.src INCLUDING ALL, extra int);")], [source]);

        var table = TableNamed(trees.Single(), "b");
        CollectionAssert.AreEqual(new[] { "id", "n", "extra" }, table.Columns.Select(static column => column.Name).ToArray());
        Assert.AreEqual("b_pkey", trees.Single().Nodes.OfType<ConstraintNode>().Single(static constraint => constraint.TableName == "b").Name);
        Assert.IsEmpty(external);
    }

    [TestMethod]
    public void AColumnCopiedTwiceIsAnError()
    {
        var (tree, _) = Expand("CREATE TABLE public.a (id int); CREATE TABLE public.b (id int, LIKE public.a);");

        Assert.IsTrue(tree.Diagnostics.Any(static diagnostic => diagnostic.Severity == SqlDiagnosticSeverity.Error && diagnostic.Message.Contains("column 'id' more than once", StringComparison.Ordinal)));
    }

    [TestMethod]
    public void TablesThatCopyEachOtherAreAnError()
    {
        var (tree, _) = Expand("CREATE TABLE public.a (LIKE public.b, x int); CREATE TABLE public.b (LIKE public.a, y int);");

        Assert.AreEqual(2, tree.Diagnostics.Count(static diagnostic => diagnostic.Severity == SqlDiagnosticSeverity.Error && diagnostic.Source == TableLikeExpander.DiagnosticSource));
    }

    [TestMethod]
    public void ATableWithoutLikeIsLeftAlone()
    {
        var trees = new[] { new PgQueryParser().Parse("CREATE TABLE public.a (id int);") };

        Assert.AreSame(trees, TableLikeExpander.Apply(trees).Trees);
    }

    private static (SqlSyntaxTree Tree, IReadOnlyList<string> External) Expand(string sql)
    {
        var (trees, external) = TableLikeExpander.Apply([new PgQueryParser().Parse(sql)]);
        return (trees.Single(), external);
    }

    private static TableNode TableNamed(SqlSyntaxTree tree, string name) => tree.Nodes.OfType<TableNode>().Single(table => table.Name == name);
}
