namespace PgProj.Parser.Tests;

/// <summary>
/// G-120: the parser carries PostgreSQL 18's grammar (NuGet <c>Npgquery</c>'s libpg_query), so 18 syntax parses instead of failing with a
/// syntax error, and, since G-121 part 2 modeled the last of the 18 features the model could not hold, it is all read into the model rather than
/// refused. This is the check that the grammar in use is 18's, and that what also existed in 16 and 17 is unaffected.
/// </summary>
[TestClass]
public sealed class PostgreSql18SyntaxTests
{
    [TestMethod]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT a_pos CHECK (a > 0) NOT ENFORCED;")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT fk FOREIGN KEY (pid) REFERENCES s.p(id) NOT ENFORCED;")]
    [DataRow("CREATE TABLE s.t (a int CHECK (a > 0) NOT ENFORCED);")]
    [DataRow("ALTER TABLE s.t ALTER CONSTRAINT c NOT ENFORCED;")]
    [DataRow("ALTER TABLE s.t ALTER CONSTRAINT c ENFORCED;")]
    [DataRow("ALTER TABLE s.room ADD CONSTRAINT pk PRIMARY KEY (id, during WITHOUT OVERLAPS);")]
    [DataRow("ALTER TABLE s.room ADD CONSTRAINT u UNIQUE (id, during WITHOUT OVERLAPS);")]
    [DataRow("CREATE TABLE s.room (id int, during tsrange, PRIMARY KEY (id, during WITHOUT OVERLAPS));")]
    [DataRow("ALTER TABLE s.c ADD CONSTRAINT fk FOREIGN KEY (id, PERIOD during) REFERENCES s.room (id, PERIOD during);")]
    [DataRow("CREATE TABLE s.g (a int, b int GENERATED ALWAYS AS (a * 2) VIRTUAL);")]
    [DataRow("CREATE TABLE s.g (a int, b int GENERATED ALWAYS AS (a * 2));")]
    [DataRow("ALTER TABLE s.n ADD CONSTRAINT nn NOT NULL a NOT VALID;")]
    [DataRow("ALTER TABLE s.n ADD NOT NULL a NOT VALID;")]
    [DataRow("CREATE TABLE s.n (a int, CONSTRAINT nn NOT NULL a);")]
    public void PostgreSql18SyntaxParsesWithoutAnError(string sql)
    {
        // Act
        var diagnostics = new PgQueryParser().Parse(sql).Diagnostics;

        // Assert
        Assert.AreEqual(0, diagnostics.Count(static d => d.Severity == SqlDiagnosticSeverity.Error), string.Join("; ", diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT a_pos CHECK (a > 0);")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT a_pos CHECK (a > 0) ENFORCED;")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT a_pos CHECK (a > 0) NOT VALID;")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT fk FOREIGN KEY (pid) REFERENCES s.p(id);")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT fk FOREIGN KEY (pid) REFERENCES s.p(id) NOT VALID DEFERRABLE INITIALLY DEFERRED;")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT u UNIQUE (a, b);")]
    [DataRow("ALTER TABLE s.t ADD CONSTRAINT pk PRIMARY KEY (a);")]
    [DataRow("CREATE TABLE s.t (a int CHECK (a > 0), b int REFERENCES s.p (id), c int UNIQUE, d int NOT NULL, CONSTRAINT nn CHECK (a > b));")]
    [DataRow("CREATE TABLE s.t (a int CONSTRAINT nn NOT NULL);")]
    [DataRow("CREATE TABLE s.g (a int, b int GENERATED ALWAYS AS (a * 2) STORED);")]
    [DataRow("CREATE TABLE s.i (a int GENERATED ALWAYS AS IDENTITY, b int GENERATED BY DEFAULT AS IDENTITY);")]
    [DataRow("CREATE DOMAIN s.d AS int CONSTRAINT pos CHECK (VALUE > 0);")]
    [DataRow("ALTER TABLE s.t ALTER CONSTRAINT c DEFERRABLE INITIALLY DEFERRED;")]
    [DataRow("CREATE TABLE s.x (a int, EXCLUDE USING gist (a WITH =));")]
    public void SyntaxThatExistedBeforePostgreSql18IsNotReported(string sql)
    {
        // Act
        var diagnostics = new PgQueryParser().Parse(sql).Diagnostics;

        // Assert
        Assert.AreEqual(0, diagnostics.Count(static d => d.Severity == SqlDiagnosticSeverity.Error), string.Join("; ", diagnostics.Select(static d => d.Message)));
    }

    [TestMethod]
    public void ARealSyntaxErrorIsStillASyntaxError()
    {
        // Act
        var error = new PgQueryParser().Parse("ALTER TABLE s.t ADD CONSTRAINT c CHECK (a > 0) NOT BOGUS;").Diagnostics.Single(static d => d.Severity == SqlDiagnosticSeverity.Error);

        // Assert
        StringAssert.Contains(error.Message, "syntax error");
    }

    [TestMethod]
    public void TheListBoundsPostgreSql18AddsToAnInListAreNotPartOfTheComparisonForm()
    {
        // Arrange: PostgreSQL 18's tree records where an IN list starts and ends; two spellings of one condition must still compare equal.
        var first = new PgQueryParser().Parse("CREATE TABLE s.t (a int, CONSTRAINT c CHECK (a IN (1, 2)));").Nodes.OfType<ConstraintNode>().Single().CheckExpressionAst;
        var second = new PgQueryParser().Parse("CREATE TABLE s.t (a int, CONSTRAINT c CHECK (a  IN  ( 1,2 )));").Nodes.OfType<ConstraintNode>().Single().CheckExpressionAst;

        // Act
        var canonicalFirst = TriggerWhenConditionCanonicalizer.Canonicalize(first, null);
        var canonicalSecond = TriggerWhenConditionCanonicalizer.Canonicalize(second, null);

        // Assert
        Assert.IsNotNull(canonicalFirst);
        Assert.AreEqual(canonicalFirst, canonicalSecond);
    }
}
