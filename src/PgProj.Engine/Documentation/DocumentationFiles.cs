using System.Text.Json;
using System.Text.Json.Serialization;

namespace PgProj.Engine.Documentation;

/// <summary>Renders the files of <c>pgproj document</c> (G-159); where they are written, and what happens to a file already there, is the shell's (G-309d).</summary>
internal static class DocumentationFiles
{
    /// <summary>The text every file <c>document</c> writes carries near its top, which is how a later run tells a file it wrote from one a person wrote.</summary>
    public const string Marker = "Generated by pgproj document";

    /// <summary>The base name of the files, which the format's extension follows.</summary>
    public const string BaseName = "database-documentation";

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DictionaryKeyPolicy = null,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) },
    };

    public static string Extension(DocFormat format) => format switch
    {
        DocFormat.Html => ".html",
        DocFormat.Markdown => ".md",
        _ => ".json",
    };

    public static string Render(DatabaseDocumentation document, DocFormat format)
    {
        ArgumentNullException.ThrowIfNull(document);

        return format switch
        {
            DocFormat.Html => DocumentationHtml.Render(document),
            DocFormat.Markdown => DocumentationMarkdown.Render(document),
            _ => JsonSerializer.Serialize(document, JsonOptions) + Environment.NewLine,
        };
    }
}
