using static PgProj.Integration.Tests.EndToEndSupport;

namespace PgProj.Integration.Tests;

/// <summary>
/// G-221 against a real server. <c>CREATE TABLE ... (LIKE source ...)</c> was deployed as a table with only its own columns, and the re-diff was empty, so
/// nothing showed it. The <c>LIKE</c> is now deployed as written, after its source and what it copies, and converges; what the source gains later is added to
/// the copy; a scaffold of the result converges; and a source in a schema the project does not model is read from the database.
/// </summary>
[TestClass]
public sealed class TableLikeEndToEndTests
{
    private const string Source = """
        CREATE TABLE public.a (id int PRIMARY KEY, n text DEFAULT 'x' NOT NULL, ident int GENERATED BY DEFAULT AS IDENTITY (START WITH 5), u int, v int,
            CHECK (id > 0), CONSTRAINT a_u_v_key UNIQUE (u) INCLUDE (v), EXCLUDE USING btree (v WITH =));
        CREATE INDEX a_lower ON public.a (lower(n));
        CREATE STATISTICS public.a_st ON u, v FROM public.a;
        COMMENT ON COLUMN public.a.n IS 'n comment';
        COMMENT ON CONSTRAINT a_id_check ON public.a IS 'ck comment';
        """;

    private const string Tables = """
        CREATE TABLE public.b (x int, LIKE public.a INCLUDING ALL, extra int);
        CREATE TABLE public.c (LIKE public.b INCLUDING DEFAULTS);
        """;

    [TestMethod]
    public async Task ALikeIsDeployedConvergesFollowsItsSourceAndIsScaffolded()
    {
        var databaseName = await CreateDatabaseAsync("g221");
        var projectDirectory = CreateProjectDirectory("g221");
        var scaffoldDirectory = Path.Combine(Path.GetTempPath(), "pgproj-g221-init-" + Guid.NewGuid().ToString("N"));
        try
        {
            var connectionString = ConnectionStringFor(databaseName);
            var projectFile = ProjectFile(projectDirectory);
            WriteSchema(projectDirectory, Source + Tables);

            var published = await RunAsync("publish", "--project", projectFile, "--target-connection", connectionString, "--execute");
            Assert.AreEqual(0, published.ExitCode, "publish --execute failed.\n" + published.Output);
            Assert.AreEqual("x,id,n,ident,u,v,extra", await ScalarTextAsync(connectionString, "SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid = 'public.b'::regclass AND attnum > 0;"));
            Assert.AreEqual(
                "a_id_check,b_pkey,b_u_v_key,b_v_excl",
                await ScalarTextAsync(connectionString, "SELECT string_agg(conname, ',' ORDER BY conname) FROM pg_constraint WHERE conrelid = 'public.b'::regclass AND contype <> 'n';"));
            Assert.AreEqual("b_lower_idx", await ScalarTextAsync(connectionString, "SELECT indexrelid::regclass::text FROM pg_index WHERE indrelid = 'public.b'::regclass AND NOT indisunique AND indexprs IS NOT NULL;"));
            Assert.AreEqual("ck comment", await ScalarTextAsync(connectionString, "SELECT obj_description(oid, 'pg_constraint') FROM pg_constraint WHERE conrelid = 'public.b'::regclass AND conname = 'a_id_check';"));
            Assert.AreEqual("x,id,n,ident,u,v,extra", await ScalarTextAsync(connectionString, "SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid = 'public.c'::regclass AND attnum > 0;"));
            await AssertDiffIsEmptyAsync(projectFile, connectionString);

            // The source gains a column, a CHECK, and an index; the table that copies it gets them as well.
            WriteSchema(projectDirectory, Source.Replace("v int,", "v int, m int, CONSTRAINT a_m CHECK (m > 0),", StringComparison.Ordinal) + "CREATE INDEX a_m_i ON public.a (m);\n" + Tables);
            var altered = await RunAsync("publish", "--project", projectFile, "--target-connection", connectionString, "--execute");
            Assert.AreEqual(0, altered.ExitCode, "the second publish failed.\n" + altered.Output);
            Assert.AreEqual("1", await ScalarTextAsync(connectionString, "SELECT count(*)::text FROM pg_constraint WHERE conrelid = 'public.b'::regclass AND conname = 'a_m';"));
            Assert.AreEqual("1", await ScalarTextAsync(connectionString, "SELECT count(*)::text FROM pg_index WHERE indexrelid = 'public.b_m_idx'::regclass;"));
            await AssertDiffIsEmptyAsync(projectFile, connectionString);

            var scaffoldProject = Path.Combine(scaffoldDirectory, "pgproj.json");
            var scaffolded = await RunAsync("init", "--project", scaffoldProject, "--source-connection", connectionString);
            Assert.AreEqual(0, scaffolded.ExitCode, scaffolded.Output);
            var scaffoldBuilt = await RunAsync("build", "--project", scaffoldProject);
            Assert.AreEqual(0, scaffoldBuilt.ExitCode, scaffoldBuilt.Output);
            await AssertDiffIsEmptyAsync(scaffoldProject, connectionString);
        }
        finally
        {
            await DropDatabaseAsync(databaseName);
            TryDeleteDirectory(projectDirectory);
            TryDeleteDirectory(scaffoldDirectory);
        }
    }

    [TestMethod]
    public async Task ASourceInASchemaTheProjectDoesNotModelIsReadFromTheDatabase()
    {
        var databaseName = await CreateDatabaseAsync("g221x");
        var projectDirectory = CreateProjectDirectory("g221x", """, "schemas": ["app"]""");
        try
        {
            var connectionString = ConnectionStringFor(databaseName);
            var projectFile = ProjectFile(projectDirectory);
            await ExecuteAsync(connectionString, "CREATE SCHEMA ext; CREATE TABLE ext.src (id int PRIMARY KEY, n text DEFAULT 'q' CHECK (n <> ''), m int); CREATE INDEX ON ext.src (m);");
            WriteSchema(projectDirectory, "CREATE SCHEMA app;\nCREATE TABLE app.b (LIKE ext.src INCLUDING ALL, extra int);\n");

            var built = await RunAsync("build", "--project", projectFile);
            Assert.AreEqual(0, built.ExitCode, built.Output);
            StringAssert.Contains(built.Output, "references missing table 'ext.src'");

            var published = await RunAsync("publish", "--project", projectFile, "--target-connection", connectionString, "--execute");
            Assert.AreEqual(0, published.ExitCode, "publish --execute failed.\n" + published.Output);
            Assert.AreEqual("id,n,m,extra", await ScalarTextAsync(connectionString, "SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid = 'app.b'::regclass AND attnum > 0;"));
            Assert.AreEqual("b_m_idx,b_pkey", await ScalarTextAsync(connectionString, "SELECT string_agg(c.relname, ',' ORDER BY c.relname) FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid WHERE i.indrelid = 'app.b'::regclass;"));
            await AssertDiffIsEmptyAsync(projectFile, connectionString);
        }
        finally
        {
            await DropDatabaseAsync(databaseName);
            TryDeleteDirectory(projectDirectory);
        }
    }
}
