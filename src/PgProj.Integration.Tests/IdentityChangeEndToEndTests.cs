using static PgProj.Integration.Tests.EndToEndSupport;

namespace PgProj.Integration.Tests;

/// <summary>
/// G-214 against a real server. An identity's options were not deployed, a change to its generation or options or adding one to a column deployed
/// nothing, a changed option restarted the sequence at 1, and dropping one failed (<c>42601</c>). Each is now made in place; identity added to a column
/// with rows starts past them; and a scaffold writes the identity's options on its column and converges.
/// </summary>
[TestClass]
public sealed class IdentityChangeEndToEndTests
{
    private const string Before = """
        CREATE TABLE public.t (
            id int GENERATED ALWAYS AS IDENTITY,
            b int GENERATED BY DEFAULT AS IDENTITY (START WITH 10),
            c int NOT NULL,
            d int GENERATED ALWAYS AS IDENTITY
        );
        """;

    private const string After = """
        CREATE TABLE public.t (
            id int GENERATED BY DEFAULT AS IDENTITY,
            b int GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5),
            c int GENERATED BY DEFAULT AS IDENTITY,
            d int
        );
        """;

    [TestMethod]
    public async Task IdentityChangesAreMadeInPlaceAndConverge()
    {
        var databaseName = await CreateDatabaseAsync("g214");
        var projectDirectory = CreateProjectDirectory("g214");
        var scaffoldDirectory = Path.Combine(Path.GetTempPath(), "pgproj-g214-init-" + Guid.NewGuid().ToString("N"));
        try
        {
            var connectionString = ConnectionStringFor(databaseName);
            var projectFile = ProjectFile(projectDirectory);
            WriteSchema(projectDirectory, Before);

            var published = await RunAsync("publish", "--project", projectFile, "--target-connection", connectionString, "--execute");
            Assert.AreEqual(0, published.ExitCode, "publish --execute failed.\n" + published.Output);
            Assert.AreEqual("10", await ScalarTextAsync(connectionString, "SELECT seqstart::text FROM pg_sequence WHERE seqrelid = pg_get_serial_sequence('public.t', 'b')::regclass;"));
            await AssertDiffIsEmptyAsync(projectFile, connectionString);

            // Rows that take b's counter forward, and c values the new identity must start after.
            await ExecuteAsync(connectionString, "INSERT INTO public.t (c) SELECT g FROM generate_series(1, 3) g;");

            WriteSchema(projectDirectory, After);
            var altered = await RunAsync("publish", "--project", projectFile, "--target-connection", connectionString, "--execute");
            Assert.AreEqual(0, altered.ExitCode, "the second publish failed.\n" + altered.Output);
            Assert.AreEqual("d", await ScalarTextAsync(connectionString, "SELECT attidentity::text FROM pg_attribute WHERE attrelid = 'public.t'::regclass AND attname = 'id';"));
            await AssertDiffIsEmptyAsync(projectFile, connectionString);

            // b kept its counter (10, 11, 12; no restart) and now steps by 5; c starts after the rows it holds; d is an ordinary column.
            Assert.AreEqual("17 4 -", await ScalarTextAsync(connectionString, "INSERT INTO public.t (d) VALUES (NULL) RETURNING b::text || ' ' || c::text || ' ' || coalesce(d::text, '-');"));
            Assert.AreEqual("5", await ScalarTextAsync(connectionString, "SELECT seqincrement::text FROM pg_sequence WHERE seqrelid = pg_get_serial_sequence('public.t', 'b')::regclass;"));

            var scaffoldProject = Path.Combine(scaffoldDirectory, "pgproj.json");
            var scaffolded = await RunAsync("init", "--project", scaffoldProject, "--source-connection", connectionString);
            Assert.AreEqual(0, scaffolded.ExitCode, scaffolded.Output);
            var tableFile = File.ReadAllText(Directory.GetFiles(scaffoldDirectory, "t.sql", SearchOption.AllDirectories).Single());
            StringAssert.Contains(tableFile, "GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5)");
            Assert.IsFalse(Directory.GetFiles(scaffoldDirectory, "*.sql", SearchOption.AllDirectories).Any(static file => File.ReadAllText(file).Contains("CREATE SEQUENCE", StringComparison.Ordinal)));
            var scaffoldBuilt = await RunAsync("build", "--project", scaffoldProject);
            Assert.AreEqual(0, scaffoldBuilt.ExitCode, scaffoldBuilt.Output);
            await AssertDiffIsEmptyAsync(scaffoldProject, connectionString);
        }
        finally
        {
            await DropDatabaseAsync(databaseName);
            TryDeleteDirectory(projectDirectory);
            TryDeleteDirectory(scaffoldDirectory);
        }
    }
}
