using PgProj.Deploy;

namespace PgProj.Cli.Tests;

/// <summary>
/// Unit tests for <see cref="SqlStatementSplitter"/> behavior as consumed by the CLI execution path.
/// Transaction-wrapped execution against a live PostgreSQL connection is covered by integration tests.
/// </summary>
[TestClass]
public sealed class SqlStatementSplitterCliIntegrationTests
{
    // These tests verify that the splitter produces the correct statement list
    // that the engine's ScriptExecution.ExecuteScriptAsync would feed to the database one-by-one
    // inside a transaction.

    [TestMethod]
    public void EmptyScriptProducesNoStatements_SoExecutionIsSkipped()
    {
        // ScriptExecution.ExecuteScriptAsync returns early when Split returns empty.
        var statements = SqlStatementSplitter.Split(string.Empty);
        Assert.HasCount(0, statements);
    }

    [TestMethod]
    public void WhitespaceScriptProducesNoStatements_SoExecutionIsSkipped()
    {
        var statements = SqlStatementSplitter.Split("  \n  \t  ");
        Assert.HasCount(0, statements);
    }

    [TestMethod]
    public void CommentOnlyScriptWithNoSemicolonProducesOneTrailingStatement()
    {
        // A script that is only comments (no real DDL, no semicolons) is treated
        // as a single trailing statement by the splitter. The engine will try to
        // execute it; the database will treat it as a no-op and succeed.
        var statements = SqlStatementSplitter.Split("-- deploy.sql\n-- generated by pgproj");
        Assert.HasCount(1, statements);
    }

    [TestMethod]
    public void TypicalMigrationScriptSplitsIntoCorrectStatementCount()
    {
        // Simulates a real publish script output: sequence + table + index.
        var script =
            """
            CREATE SEQUENCE "public"."orders_id_seq" OWNED BY "public"."orders"."id";
            CREATE TABLE "public"."orders" (
                "id" integer GENERATED ALWAYS AS IDENTITY,
                "name" text
            );
            CREATE INDEX "idx_orders_name" ON "public"."orders" ("name");
            """;

        var statements = SqlStatementSplitter.Split(script);

        // Each statement is sent as a separate NpgsqlCommand inside the transaction.
        Assert.HasCount(3, statements);
        StringAssert.Contains(statements[0], "CREATE SEQUENCE");
        StringAssert.Contains(statements[1], "CREATE TABLE");
        StringAssert.Contains(statements[2], "CREATE INDEX");
    }

    [TestMethod]
    public void FunctionBodyWithInternalSemicolonsIsOneSingleStatement()
    {
        // Ensures a CREATE FUNCTION is sent as one atomic command to the database,
        // not split at the internal semicolons inside the $$ body.
        var script =
            """
            CREATE FUNCTION "public"."notify_change"() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
              PERFORM pg_notify('change', row_to_json(NEW)::text);
              RETURN NEW;
            END;
            $$;
            """;

        var statements = SqlStatementSplitter.Split(script);

        Assert.HasCount(1, statements);
        StringAssert.Contains(statements[0], "pg_notify");
        StringAssert.Contains(statements[0], "RETURN NEW");
    }

    [TestMethod]
    public void ScriptWithPreAndPostDeployCommentsIsHandledCorrectly()
    {
        // Scripts written by pgproj include -- TODO comments for stub operations;
        // those comments should not interfere with statement splitting.
        var script =
            """
            -- TODO: Generate ALTER SQL for Table 'public.orders'.
            -- Old Node: public.orders
            -- New Node: public.orders
            CREATE TABLE "public"."products" (id integer);
            """;

        var statements = SqlStatementSplitter.Split(script);

        // The TODO comment lines have no semicolons so they stay attached to the
        // next statement (CREATE TABLE), which is what we want — one statement total.
        Assert.HasCount(1, statements);
        StringAssert.Contains(statements[0], "CREATE TABLE");
    }
}
