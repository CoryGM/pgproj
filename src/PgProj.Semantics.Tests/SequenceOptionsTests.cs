using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Semantics.Tests;

/// <summary>
/// G-57: a project may leave every sequence option implicit while the live catalog reports them all, so sequences were
/// compared on what was written and re-diffed forever. <see cref="SequenceDefinition.GetEffectiveOptions"/> resolves the
/// options as PostgreSQL does.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class SequenceOptionsTests
{
    [TestMethod]
    [DataRow("", "int8", "1", "1", "9223372036854775807", "1", "1", false)]
    [DataRow("as bigint", "int8", "1", "1", "9223372036854775807", "1", "1", false)]
    [DataRow("as integer", "int4", "1", "1", "2147483647", "1", "1", false)]
    [DataRow("as int4", "int4", "1", "1", "2147483647", "1", "1", false)]
    [DataRow("as smallint", "int2", "1", "1", "32767", "1", "1", false)]
    [DataRow("increment by -1", "int8", "-1", "-9223372036854775808", "-1", "-1", "1", false)]
    [DataRow("as integer increment by -2", "int4", "-2", "-2147483648", "-1", "-1", "1", false)]
    [DataRow("minvalue 10", "int8", "1", "10", "9223372036854775807", "10", "1", false)]
    [DataRow("maxvalue 100 increment by -1", "int8", "-1", "-9223372036854775808", "100", "100", "1", false)]
    [DataRow("start with 5 cache 20 cycle", "int8", "1", "1", "9223372036854775807", "5", "20", true)]
    [DataRow("increment by 5 minvalue 0 maxvalue 50 start with 10 cache 3 no cycle", "int8", "5", "0", "50", "10", "3", false)]
    public void EffectiveOptionsApplyPostgreSqlDefaults(string options, string type, string increment, string min, string max, string start, string cache, bool cycle)
    {
        var sequence = Build($"create sequence public.s {options};");

        var effective = sequence.GetEffectiveOptions();

        Assert.AreEqual(new SequenceOptions(type, increment, min, max, start, cache, cycle), effective, options);
    }

    /// <summary>What was written is still what is deployed: resolving defaults never rewrites the declared values.</summary>
    [TestMethod]
    public void DeclaredValuesAreLeftAsWritten()
    {
        var sequence = Build("create sequence public.s;");

        Assert.IsNull(sequence.DataType);
        Assert.IsNull(sequence.IncrementBy);
        Assert.IsNull(sequence.MinValue);
        Assert.IsNull(sequence.MaxValue);
        Assert.IsNull(sequence.StartValue);
        Assert.IsNull(sequence.CacheSize);
        Assert.IsNull(sequence.Cycle);
    }

    [TestMethod]
    [DataRow("integer", "int4")]
    [DataRow("int", "int4")]
    [DataRow("pg_catalog.int4", "int4")]
    [DataRow("smallint", "int2")]
    [DataRow("pg_catalog.int2", "int2")]
    [DataRow("bigint", "int8")]
    [DataRow("pg_catalog.int8", "int8")]
    [DataRow(null, "int8")]
    public void TypeSpellingsResolveToOneType(string? spelled, string expected)
    {
        var sequence = Build("create sequence public.s;") with { DataType = spelled };

        Assert.AreEqual(expected, sequence.GetEffectiveOptions().DataType);
    }

    [TestMethod]
    public void ValueThatIsNotAPlainIntegerIsKeptAsWritten()
    {
        var sequence = Build("create sequence public.s;") with { MaxValue = " 1e3 " };

        Assert.AreEqual("1e3", sequence.GetEffectiveOptions().MaxValue);
    }

    /// <summary>
    /// The identity sequence synthesized for an <c>integer</c> column got the bigint maximum, because the column's type arrives
    /// as <c>pg_catalog.int4</c> and only the plain spellings were matched.
    /// </summary>
    [TestMethod]
    [DataRow("integer", "2147483647")]
    [DataRow("int", "2147483647")]
    [DataRow("smallint", "32767")]
    [DataRow("bigint", "9223372036854775807")]
    public void IdentitySequenceHasTheMaximumOfItsColumnType(string columnType, string expectedMax)
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse($"create table public.t (id {columnType} generated by default as identity);")]);

        var sequence = model.Sequences.Values.Single();
        Assert.IsTrue(sequence.IsIdentityOwned);
        Assert.AreEqual(expectedMax, sequence.MaxValue);
        Assert.AreEqual(expectedMax, sequence.GetEffectiveOptions().MaxValue);
    }

    [TestMethod]
    public void SerialSequenceHasTheMaximumOfItsColumnType()
    {
        var model = new SemanticPipeline().Execute([new PgQueryParser().Parse("create table public.t (a serial, b bigserial, c smallserial);")]);

        Assert.AreEqual("2147483647", model.Sequences["public.t_a_seq"].GetEffectiveOptions().MaxValue);
        Assert.AreEqual("9223372036854775807", model.Sequences["public.t_b_seq"].GetEffectiveOptions().MaxValue);
        Assert.AreEqual("32767", model.Sequences["public.t_c_seq"].GetEffectiveOptions().MaxValue);
    }

    private static SequenceDefinition Build(string sql)
        => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]).Sequences["public.s"];
}
