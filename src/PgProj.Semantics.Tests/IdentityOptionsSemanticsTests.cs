using PgProj.Parser;

namespace PgProj.Semantics.Tests;

/// <summary>
/// G-214: an identity's options are read as written and carried to its sequence, which records which ones the column states; the rest are PostgreSQL's
/// defaults for the type and direction.
/// </summary>
[TestClass]
[DoNotParallelize]
public sealed class IdentityOptionsSemanticsTests
{
    [TestMethod]
    public void TheOptionsAndTheirTextAreRead()
    {
        var column = new PgQueryParser().Parse("CREATE TABLE public.t (id bigint GENERATED BY DEFAULT AS IDENTITY ( START WITH 100 INCREMENT BY 5 CYCLE ) PRIMARY KEY);")
            .Nodes.OfType<TableNode>().Single().Columns.Single();

        Assert.AreEqual("START WITH 100 INCREMENT BY 5 CYCLE", column.IdentityOptionsText);
        Assert.AreEqual("100", column.IdentityOptions!["start"]);
        Assert.AreEqual("5", column.IdentityOptions["increment"]);
    }

    [TestMethod]
    public void AnIdentityWithoutOptionsHasNone()
    {
        var column = new PgQueryParser().Parse("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY, b int);").Nodes.OfType<TableNode>().Single().Columns[0];

        Assert.IsNull(column.IdentityOptionsText);
        Assert.IsNull(column.IdentityOptions);
    }

    [TestMethod]
    public void TheSequenceRecordsTheStatedOptions()
    {
        var sequence = Build("CREATE TABLE public.t (id int GENERATED ALWAYS AS IDENTITY (START WITH 10 CACHE 20));").Sequences.Values.Single();

        Assert.IsTrue(sequence.IsIdentityOwned);
        CollectionAssert.AreEquivalent(new[] { nameof(SequenceDefinition.StartValue), nameof(SequenceDefinition.CacheSize) }, sequence.IdentityStatedOptions!.ToArray());
        Assert.AreEqual("10", sequence.StartValue);
        Assert.AreEqual("1", sequence.IncrementBy);
    }

    [TestMethod]
    public void ADescendingIdentityHasTheDescendingDefaults()
    {
        var sequence = Build("CREATE TABLE public.t (id smallint GENERATED ALWAYS AS IDENTITY (INCREMENT BY -1));").Sequences.Values.Single();

        Assert.AreEqual("-32768", sequence.MinValue);
        Assert.AreEqual("-1", sequence.MaxValue);
        Assert.AreEqual("-1", sequence.StartValue);
    }

    private static DatabaseModel Build(string sql) => new SemanticPipeline().Execute([new PgQueryParser().Parse(sql)]);
}
