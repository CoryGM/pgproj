namespace PgProj.Semantics.Tests;

[TestClass]
[DoNotParallelize]
public sealed class IdentityColumnSemanticsTests
{
    [TestMethod]
    public void GeneratedAlwaysIdentityColumnIsPreservedInSemanticModel()
    {
        var model = new SemanticPipeline().Execute(
            [new Parser.PgQueryParser().Parse(
                "CREATE TABLE public.orders (id integer GENERATED ALWAYS AS IDENTITY);")]);

        Assert.IsFalse(model.HasErrors, string.Join(Environment.NewLine, model.Diagnostics.Select(static d => d.Message)));

        var table = model.Tables["public.orders"];
        var column = table.Columns.Single(c => c.Name == "id");

        Assert.AreEqual("ALWAYS", column.IdentityGeneration);
    }

    [TestMethod]
    public void GeneratedByDefaultIdentityColumnIsPreservedInSemanticModel()
    {
        var model = new SemanticPipeline().Execute(
            [new Parser.PgQueryParser().Parse(
                "CREATE TABLE public.orders (id integer GENERATED BY DEFAULT AS IDENTITY);")]);

        Assert.IsFalse(model.HasErrors, string.Join(Environment.NewLine, model.Diagnostics.Select(static d => d.Message)));

        var table = model.Tables["public.orders"];
        var column = table.Columns.Single(c => c.Name == "id");

        Assert.AreEqual("BY DEFAULT", column.IdentityGeneration);
    }

    [TestMethod]
    public void NonIdentityColumnHasNullIdentityGenerationInSemanticModel()
    {
        var model = new SemanticPipeline().Execute(
            [new Parser.PgQueryParser().Parse(
                "CREATE TABLE public.orders (id integer, name text);")]);

        Assert.IsFalse(model.HasErrors, string.Join(Environment.NewLine, model.Diagnostics.Select(static d => d.Message)));

        var table = model.Tables["public.orders"];
        foreach (var column in table.Columns)
        {
            Assert.IsNull(column.IdentityGeneration, $"Column '{column.Name}' should not have IdentityGeneration set.");
        }
    }
}
