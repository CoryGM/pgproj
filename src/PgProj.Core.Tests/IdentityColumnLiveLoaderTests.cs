using PgProj.Parser;
using PgProj.Semantics;

namespace PgProj.Core.Tests;

[TestClass]
[DoNotParallelize]
public sealed class IdentityColumnLiveLoaderTests
{
    [TestMethod]
    public void GenerateSnapshotSql_EmitsGeneratedAlwaysAsIdentityForAlwaysColumn()
    {
        var snapshotSql = LiveDatabaseModelLoader.GenerateSnapshotSql(
            [new LiveSchemaSnapshot("public")],
            [new LiveTableSnapshot("public", "orders_identity_always",
                [new LiveColumnSnapshot("id", "integer", false, null, false, null, null, IdentityGeneration: "ALWAYS")])],
            [],
            []);

        StringAssert.Contains(snapshotSql, "GENERATED ALWAYS AS IDENTITY");
    }

    [TestMethod]
    public void GenerateSnapshotSql_EmitsGeneratedByDefaultAsIdentityForByDefaultColumn()
    {
        var snapshotSql = LiveDatabaseModelLoader.GenerateSnapshotSql(
            [new LiveSchemaSnapshot("public")],
            [new LiveTableSnapshot("public", "orders_identity_bydefault",
                [new LiveColumnSnapshot("id", "integer", false, null, false, null, null, IdentityGeneration: "BY DEFAULT")])],
            [],
            []);

        StringAssert.Contains(snapshotSql, "GENERATED BY DEFAULT AS IDENTITY");
    }

    [TestMethod]
    public void GenerateSnapshotSql_DoesNotEmitIdentityForNonIdentityColumn()
    {
        var snapshotSql = LiveDatabaseModelLoader.GenerateSnapshotSql(
            [new LiveSchemaSnapshot("public")],
            [new LiveTableSnapshot("public", "orders_no_identity",
                [new LiveColumnSnapshot("id", "integer", false, null, false, null, null)])],
            [],
            []);

        Assert.IsFalse(
            snapshotSql.Contains("IDENTITY", StringComparison.Ordinal),
            "Non-identity column must not emit any IDENTITY keyword.");
    }

    [TestMethod]
    public void BuildModelFromSnapshotSql_AlwaysIdentityColumnIsRoundTripped()
    {
        var snapshotSql = LiveDatabaseModelLoader.GenerateSnapshotSql(
            [new LiveSchemaSnapshot("public")],
            [new LiveTableSnapshot("public", "orders_rt_always",
                [new LiveColumnSnapshot("id", "integer", false, null, false, null, null, IdentityGeneration: "ALWAYS")])],
            [],
            []);

        var model = CreateLoader().BuildModelFromSnapshotSql(snapshotSql);

        Assert.IsFalse(model.HasErrors, string.Join(Environment.NewLine, model.Diagnostics.Select(static d => d.Message)));
        Assert.IsTrue(model.Tables.ContainsKey("public.orders_rt_always"));
        var column = model.Tables["public.orders_rt_always"].Columns.Single(static c => c.Name == "id");
        Assert.AreEqual("ALWAYS", column.IdentityGeneration);
    }

    [TestMethod]
    public void BuildModelFromSnapshotSql_ByDefaultIdentityColumnIsRoundTripped()
    {
        var snapshotSql = LiveDatabaseModelLoader.GenerateSnapshotSql(
            [new LiveSchemaSnapshot("public")],
            [new LiveTableSnapshot("public", "orders_rt_bydefault",
                [new LiveColumnSnapshot("id", "integer", false, null, false, null, null, IdentityGeneration: "BY DEFAULT")])],
            [],
            []);

        var model = CreateLoader().BuildModelFromSnapshotSql(snapshotSql);

        Assert.IsFalse(model.HasErrors, string.Join(Environment.NewLine, model.Diagnostics.Select(static d => d.Message)));
        Assert.IsTrue(model.Tables.ContainsKey("public.orders_rt_bydefault"));
        var column = model.Tables["public.orders_rt_bydefault"].Columns.Single(static c => c.Name == "id");
        Assert.AreEqual("BY DEFAULT", column.IdentityGeneration);
    }

    private static LiveDatabaseModelLoader CreateLoader()
        => new(new PgQueryParser(), new SemanticBuilder());
}
