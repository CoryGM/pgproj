COMMENT ON TABLE accounts.account IS $$
A customer account: the party that owns data and activity in the system. Accounts are soft-deleted and can be merged into another account.

@business-name: Account
$$;

COMMENT ON COLUMN accounts.account.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN accounts.account.name IS $$
The account's display name. Case-insensitive.

@business-name: Account Name
@example: Contoso Ltd
$$;

COMMENT ON COLUMN accounts.account.description IS $$
Free-text notes about the account.
$$;

COMMENT ON COLUMN accounts.account.is_deleted IS $$
Soft-delete flag. A deleted row is kept for history and ignored by normal queries; see deleted_utc.
$$;

COMMENT ON COLUMN accounts.account.is_active IS $$
Whether the row is in use. An inactive row is kept but not offered for new work.
$$;

COMMENT ON COLUMN accounts.account.merged_with_account_id IS $$
The account this one was merged into. Null for an account that has not been merged.

@see-also: accounts.account.id
$$;

COMMENT ON COLUMN accounts.account.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN accounts.account.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN accounts.account.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN accounts.account.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN accounts.account.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN accounts.account.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;
