CREATE TABLE billing.usage_event (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    subscription_id             uuid                            NOT NULL,
    quantity                    integer                         NOT NULL,
    occurred_utc                timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    idempotency_key             text                            NOT NULL,
    invoice_line_id             uuid                            NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE billing.usage_event
    ADD CONSTRAINT usage_event_pkey PRIMARY KEY (id);

ALTER TABLE billing.usage_event
    ADD CONSTRAINT usage_event_subscription_id_fkey
        FOREIGN KEY (subscription_id)
            REFERENCES billing.subscription (id);

CREATE INDEX usage_event_subscription_id ON billing.usage_event (subscription_id);

ALTER TABLE billing.usage_event
    ADD CONSTRAINT usage_event_invoice_line_id_fkey
        FOREIGN KEY (invoice_line_id)
            REFERENCES billing.invoice_line (id);

CREATE INDEX usage_event_invoice_line_id ON billing.usage_event (invoice_line_id);

ALTER TABLE billing.usage_event
    ADD CONSTRAINT usage_event_quantity_positive CHECK (quantity > 0);

ALTER TABLE billing.usage_event
    ADD CONSTRAINT usage_event_idempotency_key_key UNIQUE (subscription_id, idempotency_key);

CREATE INDEX usage_event_unbilled ON billing.usage_event (subscription_id, occurred_utc) WHERE invoice_line_id IS NULL;

COMMENT ON TABLE billing.usage_event IS $$
A metered usage report for a subscription, for example API calls. Events not yet on an invoice have a null invoice_line_id; billing.run_billing_cycle bills them and stamps the line.

@business-name: Usage Event
$$;

COMMENT ON COLUMN billing.usage_event.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN billing.usage_event.subscription_id IS $$
The subscription that used the units.

@see-also: billing.subscription.id
$$;

COMMENT ON COLUMN billing.usage_event.quantity IS $$
Units used. Always positive.
$$;

COMMENT ON COLUMN billing.usage_event.occurred_utc IS $$
When the usage happened, in UTC.
$$;

COMMENT ON COLUMN billing.usage_event.idempotency_key IS $$
A caller-chosen key that makes retries safe: reporting the same key twice for a subscription is rejected.
$$;

COMMENT ON COLUMN billing.usage_event.invoice_line_id IS $$
The invoice line the usage was billed on. Null until billed.

@see-also: billing.invoice_line.id
$$;

COMMENT ON COLUMN billing.usage_event.created_utc IS $$
When the event was recorded, in UTC. Set by the database.
$$;
