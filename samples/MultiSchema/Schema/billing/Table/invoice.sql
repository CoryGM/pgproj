CREATE TABLE billing.invoice (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    invoice_number              text                            NOT NULL        DEFAULT billing.next_invoice_number(),
    account_id                  uuid                            NOT NULL,
    subscription_id             uuid                            NULL,
    status                      billing.invoice_status          NOT NULL        DEFAULT 'draft',
    period_start                date                            NOT NULL,
    period_end                  date                            NOT NULL,
    subtotal                    numeric(12,2)                   NOT NULL        DEFAULT 0,
    tax_total                   numeric(12,2)                   NOT NULL        DEFAULT 0,
    total                       numeric(12,2)                   GENERATED ALWAYS AS (subtotal + tax_total) STORED,
    due_on                      date                            NOT NULL,
    issued_utc                  timestamp without time zone     NULL,
    paid_utc                    timestamp without time zone     NULL,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_pkey PRIMARY KEY (id);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_account_id_fkey
        FOREIGN KEY (account_id)
            REFERENCES accounts.account (id);

CREATE INDEX invoice_account_id ON billing.invoice (account_id);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_subscription_id_fkey
        FOREIGN KEY (subscription_id)
            REFERENCES billing.subscription (id);

CREATE INDEX invoice_subscription_id ON billing.invoice (subscription_id);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_invoice_number_key UNIQUE (invoice_number);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_period_order CHECK (period_end > period_start);

-- A subscription is invoiced at most once for any period.
CREATE UNIQUE INDEX invoice_one_per_subscription_period ON billing.invoice (subscription_id, period_start)
    WHERE subscription_id IS NOT NULL AND status <> 'void';

CREATE INDEX invoice_open_due ON billing.invoice (due_on) WHERE status = 'open';

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE billing.invoice
    ADD CONSTRAINT invoice_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX invoice_created_principal_id ON billing.invoice (created_principal_id);
CREATE INDEX invoice_updated_principal_id ON billing.invoice (updated_principal_id);

CREATE TRIGGER invoice_set_updated_utc
    BEFORE UPDATE ON billing.invoice
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN billing.invoice.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.invoice.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN billing.invoice.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.invoice.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE billing.invoice IS $$
A bill for an account covering one billing period. Created as a draft with its lines by billing.run_billing_cycle, then opened for payment.

@business-name: Invoice
$$;

COMMENT ON COLUMN billing.invoice.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN billing.invoice.invoice_number IS $$
The number printed on the invoice. Unique.

@example: INV-005001
$$;

COMMENT ON COLUMN billing.invoice.account_id IS $$
The account being billed.

@see-also: accounts.account.id
$$;

COMMENT ON COLUMN billing.invoice.subscription_id IS $$
The subscription the invoice is for. Null for a one-off invoice.

@see-also: billing.subscription.id
$$;

COMMENT ON COLUMN billing.invoice.status IS $$
Where the invoice is in its life cycle.
$$;

COMMENT ON COLUMN billing.invoice.period_start IS $$
First day covered by the invoice.
$$;

COMMENT ON COLUMN billing.invoice.period_end IS $$
Day the covered period ends. Exclusive.
$$;

COMMENT ON COLUMN billing.invoice.subtotal IS $$
Sum of the invoice line amounts. Maintained by the invoice_line_totals trigger.
$$;

COMMENT ON COLUMN billing.invoice.tax_total IS $$
Tax charged on the invoice.
$$;

COMMENT ON COLUMN billing.invoice.total IS $$
subtotal + tax_total. Generated.
$$;

COMMENT ON COLUMN billing.invoice.due_on IS $$
The date payment is due.
$$;

COMMENT ON COLUMN billing.invoice.issued_utc IS $$
When the invoice was opened for payment, in UTC.
$$;

COMMENT ON COLUMN billing.invoice.paid_utc IS $$
When the invoice was paid, in UTC.
$$;
