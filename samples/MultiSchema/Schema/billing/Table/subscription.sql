CREATE TABLE billing.subscription (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    account_id                  uuid                            NOT NULL,
    plan_id                     uuid                            NOT NULL,
    status                      billing.subscription_status     NOT NULL        DEFAULT 'active',
    started_on                  date                            NOT NULL        DEFAULT current_date,
    current_period_start        date                            NOT NULL,
    current_period_end          date                            NOT NULL,
    trial_end_on                date                            NULL,
    cancel_at_period_end        boolean                         NOT NULL        DEFAULT false,
    cancelled_utc               timestamp without time zone     NULL,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_pkey PRIMARY KEY (id);

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_account_id_fkey
        FOREIGN KEY (account_id)
            REFERENCES accounts.account (id);

CREATE INDEX subscription_account_id ON billing.subscription (account_id);

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_plan_id_fkey
        FOREIGN KEY (plan_id)
            REFERENCES billing.plan (id);

CREATE INDEX subscription_plan_id ON billing.subscription (plan_id);

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_period_order CHECK (current_period_end > current_period_start);

-- An account has at most one live subscription.
CREATE UNIQUE INDEX subscription_one_live_per_account ON billing.subscription (account_id)
    WHERE status IN ('trialing', 'active', 'past_due');

CREATE INDEX subscription_period_end ON billing.subscription (current_period_end) WHERE status IN ('trialing', 'active', 'past_due');

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE billing.subscription
    ADD CONSTRAINT subscription_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX subscription_created_principal_id ON billing.subscription (created_principal_id);
CREATE INDEX subscription_updated_principal_id ON billing.subscription (updated_principal_id);

CREATE TRIGGER subscription_set_updated_utc
    BEFORE UPDATE ON billing.subscription
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN billing.subscription.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.subscription.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN billing.subscription.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.subscription.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE billing.subscription IS $$
An account enrolment in a plan. The billing cycle (billing.run_billing_cycle) invoices a subscription when its current period ends and then moves the period forward.

@business-name: Subscription
$$;

COMMENT ON COLUMN billing.subscription.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN billing.subscription.account_id IS $$
The account that pays for the subscription.

@see-also: accounts.account.id
$$;

COMMENT ON COLUMN billing.subscription.plan_id IS $$
The plan the account is on.

@see-also: billing.plan.id
$$;

COMMENT ON COLUMN billing.subscription.status IS $$
Where the subscription is in its life cycle. An account can have only one trialing, active, or past-due subscription at a time.
$$;

COMMENT ON COLUMN billing.subscription.started_on IS $$
The date the subscription began.
$$;

COMMENT ON COLUMN billing.subscription.current_period_start IS $$
First day of the period currently being used.
$$;

COMMENT ON COLUMN billing.subscription.current_period_end IS $$
The day the current period ends and the next invoice is due to be raised. Exclusive.
$$;

COMMENT ON COLUMN billing.subscription.trial_end_on IS $$
When the free trial ends. Null if there was no trial.
$$;

COMMENT ON COLUMN billing.subscription.cancel_at_period_end IS $$
Whether the subscription ends when the current period does instead of renewing.
$$;

COMMENT ON COLUMN billing.subscription.cancelled_utc IS $$
When the subscription was cancelled, in UTC. Null while live.
$$;
