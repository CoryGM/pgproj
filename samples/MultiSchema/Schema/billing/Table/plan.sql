CREATE TABLE billing.plan (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    code                        citext                          NOT NULL,
    name                        citext                          NOT NULL,
    description                 citext                          NULL,
    billing_interval            billing.billing_interval        NOT NULL,
    price                       public.money_amount             NOT NULL,
    included_units              integer                         NOT NULL        DEFAULT 0,
    overage_unit_price          numeric(12,4)                   NOT NULL        DEFAULT 0,
    trial_days                  integer                         NOT NULL        DEFAULT 0,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE billing.plan
    ADD CONSTRAINT plan_pkey PRIMARY KEY (id);

ALTER TABLE billing.plan
    ADD CONSTRAINT plan_code_key UNIQUE (code);

ALTER TABLE billing.plan
    ADD CONSTRAINT plan_units_not_negative CHECK (included_units >= 0 AND overage_unit_price >= 0 AND trial_days >= 0);

ALTER TABLE billing.plan
    ADD CONSTRAINT plan_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE billing.plan
    ADD CONSTRAINT plan_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX plan_created_principal_id ON billing.plan (created_principal_id);
CREATE INDEX plan_updated_principal_id ON billing.plan (updated_principal_id);

CREATE TRIGGER plan_set_updated_utc
    BEFORE UPDATE ON billing.plan
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN billing.plan.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.plan.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN billing.plan.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.plan.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE billing.plan IS $$
A subscription plan: a recurring price for a billing interval, with an allowance of usage units and a per-unit price beyond it.

@business-name: Plan
$$;

COMMENT ON COLUMN billing.plan.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN billing.plan.code IS $$
A short, stable identifier. Unique.

@example: pro-monthly
$$;

COMMENT ON COLUMN billing.plan.name IS $$
The display name.
$$;

COMMENT ON COLUMN billing.plan.description IS $$
What the plan includes.
$$;

COMMENT ON COLUMN billing.plan.billing_interval IS $$
How often the plan is billed.
$$;

COMMENT ON COLUMN billing.plan.price IS $$
The recurring charge for one billing interval.
$$;

COMMENT ON COLUMN billing.plan.included_units IS $$
Usage units covered by the price each interval.
$$;

COMMENT ON COLUMN billing.plan.overage_unit_price IS $$
Price per usage unit beyond included_units, to four decimal places.
$$;

COMMENT ON COLUMN billing.plan.trial_days IS $$
Length of the free trial in days. Zero for no trial.
$$;

COMMENT ON COLUMN billing.plan.is_active IS $$
Whether new subscriptions can choose the plan.
$$;
