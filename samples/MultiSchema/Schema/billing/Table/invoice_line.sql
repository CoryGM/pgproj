CREATE TABLE billing.invoice_line (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    invoice_id                  uuid                            NOT NULL,
    line_number                 integer                         NOT NULL,
    kind                        billing.invoice_line_kind       NOT NULL,
    description                 citext                          NOT NULL,
    quantity                    numeric(12,3)                   NOT NULL        DEFAULT 1,
    unit_price                  numeric(12,4)                   NOT NULL,
    amount                      numeric(12,2)                   GENERATED ALWAYS AS (round(quantity * unit_price, 2)) STORED,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_pkey PRIMARY KEY (id);

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_invoice_id_fkey
        FOREIGN KEY (invoice_id)
            REFERENCES billing.invoice (id);

CREATE INDEX invoice_line_invoice_id ON billing.invoice_line (invoice_id);

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_invoice_id_line_number_key UNIQUE (invoice_id, line_number);

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_quantity_positive CHECK (quantity > 0);

CREATE TRIGGER invoice_line_totals
    AFTER INSERT OR DELETE OR UPDATE OF quantity, unit_price ON billing.invoice_line
    FOR EACH ROW
    EXECUTE FUNCTION billing.invoice_line_changed();

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE billing.invoice_line
    ADD CONSTRAINT invoice_line_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX invoice_line_created_principal_id ON billing.invoice_line (created_principal_id);
CREATE INDEX invoice_line_updated_principal_id ON billing.invoice_line (updated_principal_id);

CREATE TRIGGER invoice_line_set_updated_utc
    BEFORE UPDATE ON billing.invoice_line
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN billing.invoice_line.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.invoice_line.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN billing.invoice_line.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN billing.invoice_line.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE billing.invoice_line IS $$
One charge or credit on an invoice: the plan fee, metered usage beyond the allowance, a proration, or a credit. Credits have a negative unit price.

@business-name: Invoice Line
$$;

