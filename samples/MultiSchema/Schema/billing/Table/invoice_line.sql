The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN billing.invoice_line.invoice_id IS $$
The invoice the line belongs to.

@see-also: billing.invoice.id
$$;

COMMENT ON COLUMN billing.invoice_line.line_number IS $$
Position within the invoice, starting at 1.
$$;

COMMENT ON COLUMN billing.invoice_line.kind IS $$
What the line charges for.
$$;

COMMENT ON COLUMN billing.invoice_line.description IS $$
Text shown on the invoice.
$$;

COMMENT ON COLUMN billing.invoice_line.quantity IS $$
How many units are charged. Always positive; a credit uses a negative unit price instead.
$$;

COMMENT ON COLUMN billing.invoice_line.unit_price IS $$
Price per unit to four decimal places. Negative for a credit.
$$;

COMMENT ON COLUMN billing.invoice_line.amount IS $$
quantity * unit_price rounded to cents. Generated.
$$;
