CREATE TABLE sales.address (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    customer_id                 uuid                            NOT NULL,
    kind                        sales.address_kind              NOT NULL,
    recipient                   citext                          NOT NULL,
    line1                       text                            NOT NULL,
    line2                       text                            NULL,
    city                        text                            NOT NULL,
    region                      text                            NULL,
    postal_code                 text                            NOT NULL,
    country_code                char(2)                         NOT NULL        DEFAULT 'US',
    is_default                  boolean                         NOT NULL        DEFAULT false,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.address
    ADD CONSTRAINT address_pkey PRIMARY KEY (id);

ALTER TABLE sales.address
    ADD CONSTRAINT address_customer_id_fkey
        FOREIGN KEY (customer_id)
            REFERENCES sales.customer (id);

CREATE INDEX address_customer_id ON sales.address (customer_id);

-- A customer has at most one default address of each kind.
CREATE UNIQUE INDEX address_one_default_per_kind ON sales.address (customer_id, kind) WHERE is_default;

ALTER TABLE sales.address
    ADD CONSTRAINT address_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE sales.address
    ADD CONSTRAINT address_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX address_created_principal_id ON sales.address (created_principal_id);
CREATE INDEX address_updated_principal_id ON sales.address (updated_principal_id);

CREATE TRIGGER address_set_updated_utc
    BEFORE UPDATE ON sales.address
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN sales.address.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.address.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN sales.address.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.address.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

