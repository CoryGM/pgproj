CREATE TABLE sales.order_status_history (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    order_id                    uuid                            NOT NULL,
    from_status                 sales.order_status              NULL,
    to_status                   sales.order_status              NOT NULL,
    changed_principal_id        uuid                            NOT NULL,
    changed_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.order_status_history
    ADD CONSTRAINT order_status_history_pkey PRIMARY KEY (id);

ALTER TABLE sales.order_status_history
    ADD CONSTRAINT order_status_history_order_id_fkey
        FOREIGN KEY (order_id)
            REFERENCES sales.order_header (id);

CREATE INDEX order_status_history_order_id ON sales.order_status_history (order_id);

ALTER TABLE sales.order_status_history
    ADD CONSTRAINT order_status_history_changed_principal_id_fkey
        FOREIGN KEY (changed_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX order_status_history_changed_principal_id ON sales.order_status_history (changed_principal_id);

CREATE INDEX order_status_history_order_changed ON sales.order_status_history (order_id, changed_utc);

COMMENT ON TABLE sales.order_status_history IS $$
The audit trail of an order: one row when it is created and one for each status change. Written only by the order_header_status_history trigger.

@business-name: Order Status History
$$;

COMMENT ON COLUMN sales.order_status_history.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN sales.order_status_history.order_id IS $$
The order whose status changed.

@see-also: sales.order_header.id
$$;

COMMENT ON COLUMN sales.order_status_history.from_status IS $$
The status before the change. Null for the first row of an order.
$$;

COMMENT ON COLUMN sales.order_status_history.to_status IS $$
The status after the change.
$$;

COMMENT ON COLUMN sales.order_status_history.changed_principal_id IS $$
The principal that made the change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.order_status_history.changed_utc IS $$
When the change was made, in UTC.
$$;
