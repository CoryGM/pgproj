CREATE TABLE sales.discount_code (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    code                        citext                          NOT NULL,
    description                 citext                          NULL,
    percent_off                 numeric(5,2)                    NULL,
    amount_off                  public.money_amount             NULL,
    minimum_subtotal            public.money_amount             NOT NULL        DEFAULT 0,
    valid_from_utc              timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    valid_to_utc                timestamp without time zone     NULL,
    max_uses                    integer                         NULL,
    used_count                  integer                         NOT NULL        DEFAULT 0,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_pkey PRIMARY KEY (id);

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_code_key UNIQUE (code);

-- Exactly one of percent_off and amount_off is set.
ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_one_kind CHECK ((percent_off IS NULL) <> (amount_off IS NULL));

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_percent_range CHECK (percent_off IS NULL OR (percent_off > 0 AND percent_off <= 100));

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_valid_range CHECK (valid_to_utc IS NULL OR valid_to_utc > valid_from_utc);

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_uses_within_max CHECK (used_count >= 0 AND (max_uses IS NULL OR used_count <= max_uses));

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE sales.discount_code
    ADD CONSTRAINT discount_code_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX discount_code_created_principal_id ON sales.discount_code (created_principal_id);
CREATE INDEX discount_code_updated_principal_id ON sales.discount_code (updated_principal_id);

CREATE TRIGGER discount_code_set_updated_utc
    BEFORE UPDATE ON sales.discount_code
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN sales.discount_code.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.discount_code.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN sales.discount_code.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.discount_code.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE sales.discount_code IS $$
A promotion code a customer can apply to an order, worth either a percentage or a fixed amount off the order subtotal.

@business-name: Discount Code
$$;

COMMENT ON COLUMN sales.discount_code.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN sales.discount_code.code IS $$
The code the customer types. Unique, case-insensitive.

@example: WELCOME10
$$;

COMMENT ON COLUMN sales.discount_code.description IS $$
What the promotion is for.
$$;

COMMENT ON COLUMN sales.discount_code.percent_off IS $$
Percentage taken off the subtotal, from 0.01 to 100. Null when the code is a fixed amount.
$$;

COMMENT ON COLUMN sales.discount_code.amount_off IS $$
Fixed amount taken off the subtotal. Null when the code is a percentage.
$$;

COMMENT ON COLUMN sales.discount_code.minimum_subtotal IS $$
The order subtotal must be at least this for the code to apply.
$$;

COMMENT ON COLUMN sales.discount_code.valid_from_utc IS $$
When the code becomes usable, in UTC.
$$;

COMMENT ON COLUMN sales.discount_code.valid_to_utc IS $$
When the code stops being usable, in UTC. Null for no expiry.
$$;

COMMENT ON COLUMN sales.discount_code.max_uses IS $$
How many orders may use the code. Null for unlimited.
$$;

COMMENT ON COLUMN sales.discount_code.used_count IS $$
How many orders have used the code. Incremented when an order is placed.
$$;

COMMENT ON COLUMN sales.discount_code.is_active IS $$
Whether the code can be applied at all.
$$;
