CREATE TABLE sales.customer (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    account_id                  uuid                            NOT NULL,
    email                       citext                          NOT NULL,
    display_name                citext                          NOT NULL,
    phone                       text                            NULL,
    marketing_opt_in            boolean                         NOT NULL        DEFAULT false,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_pkey PRIMARY KEY (id);

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_account_id_fkey
        FOREIGN KEY (account_id)
            REFERENCES accounts.account (id);

CREATE INDEX customer_account_id ON sales.customer (account_id);

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_email_key UNIQUE (email);

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_email_format CHECK (email::text LIKE '%_@_%.__%');

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE sales.customer
    ADD CONSTRAINT customer_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX customer_created_principal_id ON sales.customer (created_principal_id);
CREATE INDEX customer_updated_principal_id ON sales.customer (updated_principal_id);

CREATE TRIGGER customer_set_updated_utc
    BEFORE UPDATE ON sales.customer
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN sales.customer.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.customer.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN sales.customer.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.customer.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE sales.customer IS $$
A person or company that buys from the store. Each customer belongs to an account, which also owns their subscriptions and invoices.

@business-name: Customer
