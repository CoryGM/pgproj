CREATE TABLE sales.order_line (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    order_id                    uuid                            NOT NULL,
    line_number                 integer                         NOT NULL,
    product_id                  uuid                            NOT NULL,
    description                 citext                          NOT NULL,
    quantity                    integer                         NOT NULL,
    unit_price                  public.money_amount             NOT NULL,
    tax_rate                    numeric(5,4)                    NOT NULL        DEFAULT 0.0000,
    line_total                  numeric(12,2)                   GENERATED ALWAYS AS (quantity * unit_price) STORED,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_pkey PRIMARY KEY (id);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_order_id_fkey
        FOREIGN KEY (order_id)
            REFERENCES sales.order_header (id);

CREATE INDEX order_line_order_id ON sales.order_line (order_id);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_product_id_fkey
        FOREIGN KEY (product_id)
            REFERENCES catalog.product (id);

CREATE INDEX order_line_product_id ON sales.order_line (product_id);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_order_id_line_number_key UNIQUE (order_id, line_number);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_quantity_positive CHECK (quantity > 0);

CREATE TRIGGER order_line_lock
    BEFORE INSERT OR DELETE OR UPDATE OF product_id, quantity, unit_price ON sales.order_line
    FOR EACH ROW
    EXECUTE FUNCTION sales.guard_order_line_change();

CREATE TRIGGER order_line_totals
    AFTER INSERT OR DELETE OR UPDATE OF quantity, unit_price, tax_rate ON sales.order_line
    FOR EACH ROW
    EXECUTE FUNCTION sales.order_line_changed();

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE sales.order_line
    ADD CONSTRAINT order_line_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX order_line_created_principal_id ON sales.order_line (created_principal_id);
CREATE INDEX order_line_updated_principal_id ON sales.order_line (updated_principal_id);

CREATE TRIGGER order_line_set_updated_utc
    BEFORE UPDATE ON sales.order_line
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN sales.order_line.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.order_line.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN sales.order_line.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.order_line.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE sales.order_line IS $$
One product and quantity on an order. The description, price, and tax rate are copied from the product when the line is added so later catalog changes do not rewrite history. Lines can only change while the order is a draft.

@business-name: Order Line
$$;

COMMENT ON COLUMN sales.order_line.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN sales.order_line.order_id IS $$
The order the line belongs to.

@see-also: sales.order_header.id
$$;

COMMENT ON COLUMN sales.order_line.line_number IS $$
Position of the line within the order, starting at 1. Unique per order.
$$;

COMMENT ON COLUMN sales.order_line.product_id IS $$
The product ordered.

@see-also: catalog.product.id
$$;

COMMENT ON COLUMN sales.order_line.description IS $$
The product name at the time of ordering.
$$;

COMMENT ON COLUMN sales.order_line.quantity IS $$
Units ordered. Always positive.
$$;

COMMENT ON COLUMN sales.order_line.unit_price IS $$
Price of one unit at the time of ordering, before tax.

@see-also: catalog.price_at
$$;

COMMENT ON COLUMN sales.order_line.tax_rate IS $$
Tax rate at the time of ordering, as a fraction.
$$;

COMMENT ON COLUMN sales.order_line.line_total IS $$
quantity * unit_price, before tax. Generated.
$$;
