CREATE TABLE sales.payment (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    order_id                    uuid                            NOT NULL,
    method                      sales.payment_method            NOT NULL,
    status                      sales.payment_status            NOT NULL        DEFAULT 'pending',
    amount                      public.money_amount             NOT NULL,
    external_reference          text                            NULL,
    processed_utc               timestamp without time zone     NULL,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_pkey PRIMARY KEY (id);

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_order_id_fkey
        FOREIGN KEY (order_id)
            REFERENCES sales.order_header (id);

CREATE INDEX payment_order_id ON sales.payment (order_id);

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_amount_positive CHECK (amount > 0);

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_processed_when_settled CHECK ((status = 'pending') = (processed_utc IS NULL));

CREATE UNIQUE INDEX payment_external_reference ON sales.payment (method, external_reference) WHERE external_reference IS NOT NULL;

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE sales.payment
    ADD CONSTRAINT payment_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX payment_created_principal_id ON sales.payment (created_principal_id);
CREATE INDEX payment_updated_principal_id ON sales.payment (updated_principal_id);

CREATE TRIGGER payment_set_updated_utc
    BEFORE UPDATE ON sales.payment
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN sales.payment.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.payment.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN sales.payment.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN sales.payment.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE sales.payment IS $$
One attempt to pay for an order. An order is paid when its captured payments cover its total; see sales.record_payment.

@business-name: Payment
$$;

COMMENT ON COLUMN sales.payment.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN sales.payment.order_id IS $$
The order being paid for.

@see-also: sales.order_header.id
$$;

COMMENT ON COLUMN sales.payment.method IS $$
How the customer paid.
$$;

COMMENT ON COLUMN sales.payment.status IS $$
The state of the payment. Only captured payments count toward the order total.
$$;

COMMENT ON COLUMN sales.payment.amount IS $$
The amount of this payment. Always positive.
$$;

COMMENT ON COLUMN sales.payment.external_reference IS $$
The payment processor reference for the transaction. Unique per method.
$$;

COMMENT ON COLUMN sales.payment.processed_utc IS $$
When the payment left the pending state, in UTC. Null while pending.
$$;
