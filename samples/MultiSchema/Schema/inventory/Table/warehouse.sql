CREATE TABLE inventory.warehouse (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    code                        citext                          NOT NULL,
    name                        citext                          NOT NULL,
    city                        citext                          NULL,
    country_code                char(2)                         NOT NULL        DEFAULT 'US',
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE inventory.warehouse
    ADD CONSTRAINT warehouse_pkey PRIMARY KEY (id);

ALTER TABLE inventory.warehouse
    ADD CONSTRAINT warehouse_code_key UNIQUE (code);

ALTER TABLE inventory.warehouse
    ADD CONSTRAINT warehouse_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE inventory.warehouse
    ADD CONSTRAINT warehouse_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX warehouse_created_principal_id ON inventory.warehouse (created_principal_id);
CREATE INDEX warehouse_updated_principal_id ON inventory.warehouse (updated_principal_id);

CREATE TRIGGER warehouse_set_updated_utc
    BEFORE UPDATE ON inventory.warehouse
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN inventory.warehouse.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN inventory.warehouse.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN inventory.warehouse.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN inventory.warehouse.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE inventory.warehouse IS $$
A place stock is held and shipped from.

@business-name: Warehouse
$$;

COMMENT ON COLUMN inventory.warehouse.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN inventory.warehouse.code IS $$
A short identifier for the warehouse. Unique.

@example: DAL-01
$$;

COMMENT ON COLUMN inventory.warehouse.name IS $$
The display name.
$$;

COMMENT ON COLUMN inventory.warehouse.city IS $$
The city the warehouse is in.
$$;

COMMENT ON COLUMN inventory.warehouse.country_code IS $$
ISO 3166-1 alpha-2 country code.
$$;

COMMENT ON COLUMN inventory.warehouse.is_active IS $$
Whether the warehouse can hold and ship stock.
$$;
