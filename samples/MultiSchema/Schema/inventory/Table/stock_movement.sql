CREATE TABLE inventory.stock_movement (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    product_id                  uuid                            NOT NULL,
    warehouse_id                uuid                            NOT NULL,
    movement_type               inventory.movement_type         NOT NULL,
    quantity_change             integer                         NOT NULL,
    order_line_id               uuid                            NULL,
    reason                      citext                          NULL,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_pkey PRIMARY KEY (id);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_product_id_fkey
        FOREIGN KEY (product_id)
            REFERENCES catalog.product (id);

CREATE INDEX stock_movement_product_id ON inventory.stock_movement (product_id);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_warehouse_id_fkey
        FOREIGN KEY (warehouse_id)
            REFERENCES inventory.warehouse (id);

CREATE INDEX stock_movement_warehouse_id ON inventory.stock_movement (warehouse_id);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX stock_movement_created_principal_id ON inventory.stock_movement (created_principal_id);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_quantity_nonzero CHECK (quantity_change <> 0);

ALTER TABLE inventory.stock_movement
    ADD CONSTRAINT stock_movement_sign_matches_type CHECK (
        (movement_type = 'sale' AND quantity_change < 0)
        OR (movement_type IN ('receipt', 'return') AND quantity_change > 0)
        OR movement_type = 'adjustment'
    );

CREATE INDEX stock_movement_product_created ON inventory.stock_movement (product_id, created_utc);
CREATE INDEX stock_movement_order_line_id ON inventory.stock_movement (order_line_id) WHERE order_line_id IS NOT NULL;

CREATE TRIGGER stock_movement_apply
    AFTER INSERT ON inventory.stock_movement
    FOR EACH ROW
    EXECUTE FUNCTION inventory.apply_stock_movement();

CREATE TRIGGER stock_movement_immutable
    BEFORE UPDATE OR DELETE ON inventory.stock_movement
    FOR EACH ROW
    EXECUTE FUNCTION inventory.reject_stock_movement_change();

COMMENT ON TABLE inventory.stock_movement IS $$
The append-only ledger of every change to stock. Corrections are made by inserting a compensating row, never by editing or deleting one.

@business-name: Stock Movement
$$;

COMMENT ON COLUMN inventory.stock_movement.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN inventory.stock_movement.product_id IS $$
The product whose stock changed.

@see-also: catalog.product.id
$$;

COMMENT ON COLUMN inventory.stock_movement.warehouse_id IS $$
The warehouse whose stock changed.

@see-also: inventory.warehouse.id
$$;

COMMENT ON COLUMN inventory.stock_movement.movement_type IS $$
Why stock changed. A sale is always negative; a receipt or return is always positive (enforced by the stock_movement_sign_matches_type check).
$$;

COMMENT ON COLUMN inventory.stock_movement.quantity_change IS $$
Units added (positive) or removed (negative). Never zero.
$$;

COMMENT ON COLUMN inventory.stock_movement.order_line_id IS $$
The order line that caused the movement, for sales and returns. Null otherwise. Not a foreign key, so the ledger outlives the order.

@see-also: sales.order_line.id
$$;

COMMENT ON COLUMN inventory.stock_movement.reason IS $$
Free-text explanation, mainly for adjustments.
$$;

COMMENT ON COLUMN inventory.stock_movement.created_principal_id IS $$
The principal that recorded the movement.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN inventory.stock_movement.created_utc IS $$
When the movement was recorded, in UTC. Set by the database.
$$;
