CREATE TABLE inventory.stock_level (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    product_id                  uuid                            NOT NULL,
    warehouse_id                uuid                            NOT NULL,
    quantity_on_hand            integer                         NOT NULL        DEFAULT 0,
    reorder_point               integer                         NOT NULL        DEFAULT 0,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_pkey PRIMARY KEY (id);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_product_id_fkey
        FOREIGN KEY (product_id)
            REFERENCES catalog.product (id);

CREATE INDEX stock_level_product_id ON inventory.stock_level (product_id);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_warehouse_id_fkey
        FOREIGN KEY (warehouse_id)
            REFERENCES inventory.warehouse (id);

CREATE INDEX stock_level_warehouse_id ON inventory.stock_level (warehouse_id);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_product_id_warehouse_id_key UNIQUE (product_id, warehouse_id);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_on_hand_not_negative CHECK (quantity_on_hand >= 0);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_reorder_point_not_negative CHECK (reorder_point >= 0);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE inventory.stock_level
    ADD CONSTRAINT stock_level_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX stock_level_created_principal_id ON inventory.stock_level (created_principal_id);
CREATE INDEX stock_level_updated_principal_id ON inventory.stock_level (updated_principal_id);

CREATE TRIGGER stock_level_set_updated_utc
    BEFORE UPDATE ON inventory.stock_level
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN inventory.stock_level.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN inventory.stock_level.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN inventory.stock_level.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN inventory.stock_level.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE inventory.stock_level IS $$
The quantity of one product held in one warehouse. Maintained by the stock_movement_apply trigger from inventory.stock_movement; never updated directly.

@business-name: Stock Level
$$;

COMMENT ON COLUMN inventory.stock_level.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN inventory.stock_level.product_id IS $$
The product held.

@see-also: catalog.product.id
$$;

COMMENT ON COLUMN inventory.stock_level.warehouse_id IS $$
The warehouse holding it.

@see-also: inventory.warehouse.id
$$;

COMMENT ON COLUMN inventory.stock_level.quantity_on_hand IS $$
Units physically in the warehouse. Never negative.
$$;

COMMENT ON COLUMN inventory.stock_level.reorder_point IS $$
When quantity_on_hand falls to this level or below the product is due for reordering; see reporting.mv_low_stock.
$$;
