CREATE TABLE catalog.product (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    category_id                 uuid                            NOT NULL,
    sku                         citext                          NOT NULL,
    name                        citext                          NOT NULL,
    description                 citext                          NULL,
    unit_price                  public.money_amount             NOT NULL,
    tax_rate                    numeric(5,4)                    NOT NULL        DEFAULT 0.0000,
    weight_grams                integer                         NULL,
    attributes                  jsonb                           NOT NULL        DEFAULT '{}'::jsonb,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    search_vector               tsvector                        GENERATED ALWAYS AS (
                                    setweight(to_tsvector('english'::regconfig, coalesce(name::text, '')), 'A') ||
                                    setweight(to_tsvector('english'::regconfig, coalesce(description::text, '')), 'B')
                                ) STORED,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_pkey PRIMARY KEY (id);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_category_id_fkey
        FOREIGN KEY (category_id)
            REFERENCES catalog.category (id);

CREATE INDEX product_category_id ON catalog.product (category_id);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_sku_key UNIQUE (sku);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_tax_rate_range CHECK (tax_rate >= 0 AND tax_rate < 1);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_weight_positive CHECK (weight_grams IS NULL OR weight_grams > 0);

CREATE INDEX product_search_vector ON catalog.product USING gin (search_vector);
CREATE INDEX product_attributes ON catalog.product USING gin (attributes jsonb_path_ops);
CREATE INDEX product_active_name ON catalog.product (name) WHERE is_active;

CREATE TRIGGER product_record_price_history
    AFTER INSERT OR UPDATE OF unit_price ON catalog.product
    FOR EACH ROW
    EXECUTE FUNCTION catalog.record_price_history();

ALTER TABLE catalog.product
    ADD CONSTRAINT product_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE catalog.product
    ADD CONSTRAINT product_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX product_created_principal_id ON catalog.product (created_principal_id);
CREATE INDEX product_updated_principal_id ON catalog.product (updated_principal_id);

CREATE TRIGGER product_set_updated_utc
    BEFORE UPDATE ON catalog.product
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN catalog.product.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN catalog.product.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN catalog.product.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN catalog.product.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE catalog.product IS $$
Something the store sells. The current price lives here; every price the product has had is kept in catalog.price_history.

@business-name: Product
$$;

COMMENT ON COLUMN catalog.product.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN catalog.product.category_id IS $$
The category the product is listed under.

@see-also: catalog.category.id
$$;

COMMENT ON COLUMN catalog.product.sku IS $$
The stock keeping unit: the code staff and suppliers use. Unique, case-insensitive.

@business-name: SKU
@example: TENT-2P-GRN
$$;

COMMENT ON COLUMN catalog.product.name IS $$
The display name shown in the store.

@business-name: Product Name
@example: Trailhead 2-Person Tent
$$;

COMMENT ON COLUMN catalog.product.description IS $$
Marketing description. Searched together with the name.
$$;

COMMENT ON COLUMN catalog.product.unit_price IS $$
The current selling price of one unit, before tax.

@see-also: catalog.price_at
$$;

COMMENT ON COLUMN catalog.product.tax_rate IS $$
The sales tax rate as a fraction, for example 0.0825 for 8.25 percent.

@example: 0.0825
$$;

COMMENT ON COLUMN catalog.product.weight_grams IS $$
Shipping weight in grams. Null when not recorded.
$$;

COMMENT ON COLUMN catalog.product.attributes IS $$
Free-form product attributes such as colour or size, as JSON. Indexed for containment queries.

@example: {"colour": "green", "capacity": 2}
$$;

COMMENT ON COLUMN catalog.product.is_active IS $$
Whether the product can be added to new orders.
$$;

COMMENT ON COLUMN catalog.product.search_vector IS $$
Generated full-text search vector over name (weight A) and description (weight B).
$$;
