CREATE TABLE catalog.price_history (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    product_id                  uuid                            NOT NULL,
    unit_price                  public.money_amount             NOT NULL,
    valid_from_utc              timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    valid_to_utc                timestamp without time zone     NULL
);

ALTER TABLE catalog.price_history
    ADD CONSTRAINT price_history_pkey PRIMARY KEY (id);

ALTER TABLE catalog.price_history
    ADD CONSTRAINT price_history_product_id_fkey
        FOREIGN KEY (product_id)
            REFERENCES catalog.product (id);

CREATE INDEX price_history_product_id ON catalog.price_history (product_id);

ALTER TABLE catalog.price_history
    ADD CONSTRAINT price_history_valid_range CHECK (valid_to_utc IS NULL OR valid_to_utc >= valid_from_utc);

-- A product has at most one open-ended (current) price row.
CREATE UNIQUE INDEX price_history_one_current ON catalog.price_history (product_id) WHERE valid_to_utc IS NULL;
CREATE INDEX price_history_product_valid_from ON catalog.price_history (product_id, valid_from_utc DESC);

COMMENT ON TABLE catalog.price_history IS $$
Every price a product has had and the period it applied. Written only by the product_record_price_history trigger; never edited by hand.

@business-name: Price History
$$;

COMMENT ON COLUMN catalog.price_history.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN catalog.price_history.product_id IS $$
The product the price belongs to.

@see-also: catalog.product.id
$$;

COMMENT ON COLUMN catalog.price_history.unit_price IS $$
The unit price during the period.
$$;

COMMENT ON COLUMN catalog.price_history.valid_from_utc IS $$
When the price took effect, in UTC.
$$;

COMMENT ON COLUMN catalog.price_history.valid_to_utc IS $$
When the price stopped applying, in UTC. Null for the current price.
$$;
