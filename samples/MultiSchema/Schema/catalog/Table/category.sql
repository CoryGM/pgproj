CREATE TABLE catalog.category (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    parent_category_id          uuid                            NULL,
    code                        citext                          NOT NULL,
    name                        citext                          NOT NULL,
    description                 citext                          NULL,
    sort_order                  integer                         NOT NULL        DEFAULT 0,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id        uuid                            NOT NULL,
    created_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now(),
    updated_principal_id        uuid                            NOT NULL,
    updated_utc                 timestamp without time zone     NOT NULL        DEFAULT public.utc_now()
);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_pkey PRIMARY KEY (id);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_parent_category_id_fkey
        FOREIGN KEY (parent_category_id)
            REFERENCES catalog.category (id);

CREATE INDEX category_parent_category_id ON catalog.category (parent_category_id);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_code_key UNIQUE (code);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_not_own_parent CHECK (parent_category_id IS DISTINCT FROM id);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_created_principal_id_fkey
        FOREIGN KEY (created_principal_id)
            REFERENCES identity.principal (id);

ALTER TABLE catalog.category
    ADD CONSTRAINT category_updated_principal_id_fkey
        FOREIGN KEY (updated_principal_id)
            REFERENCES identity.principal (id);

CREATE INDEX category_created_principal_id ON catalog.category (created_principal_id);
CREATE INDEX category_updated_principal_id ON catalog.category (updated_principal_id);

CREATE TRIGGER category_set_updated_utc
    BEFORE UPDATE ON catalog.category
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_utc();

COMMENT ON COLUMN catalog.category.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN catalog.category.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN catalog.category.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN catalog.category.updated_utc IS $$
When the row was last changed, in UTC. Maintained by the set_updated_utc trigger.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON TABLE catalog.category IS $$
A node in the product category tree. A category with no parent is a root; see catalog.v_category_tree for the flattened hierarchy.

@business-name: Product Category
$$;

COMMENT ON COLUMN catalog.category.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.
$$;

COMMENT ON COLUMN catalog.category.parent_category_id IS $$
The category this one sits under. Null for a root category.
$$;

COMMENT ON COLUMN catalog.category.code IS $$
A short, stable, URL-friendly identifier. Unique.
$$;

COMMENT ON COLUMN catalog.category.name IS $$
The display name shown in the store.
$$;

COMMENT ON COLUMN catalog.category.description IS $$
Free-text description of what belongs in the category.
$$;

COMMENT ON COLUMN catalog.category.sort_order IS $$
Position among sibling categories; lower sorts first.
$$;

COMMENT ON COLUMN catalog.category.is_active IS $$
Whether the category is shown in the store.
$$;
