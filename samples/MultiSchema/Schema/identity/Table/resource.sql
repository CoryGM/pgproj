CREATE TABLE identity.resource (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    code                        citext                          NOT NULL,
    name                        citext                          NOT NULL,
    description                 citext                          NULL,
    is_deleted                  boolean                         NOT NULL        DEFAULT false,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id		uuid							NOT NULL,
	created_utc					timestamp without time zone		NOT NULL 	    DEFAULT public.utc_now(), 
	updated_principal_id		uuid							NOT NULL,
	updated_utc					timestamp without time zone		NOT NULL	    DEFAULT public.utc_now(),
	deleted_principal_id		uuid							NULL,
	deleted_utc					timestamp without time zone		NULL
);

ALTER TABLE identity.resource 
    ADD CONSTRAINT resource_pkey PRIMARY KEY (id);

CREATE INDEX resource_code ON identity.resource (code);
CREATE INDEX resource_created_principal_id ON identity.resource (created_principal_id);
CREATE INDEX resource_created_utc ON identity.resource (created_utc);
CREATE INDEX resource_updated_principal_id ON identity.resource (updated_principal_id);
CREATE INDEX resource_updated_utc ON identity.resource (updated_utc);
CREATE INDEX resource_deleted_principal_id ON identity.resource (deleted_principal_id);
CREATE INDEX resource_deleted_utc ON identity.resource (deleted_utc);

COMMENT ON TABLE identity.resource IS $$
Something access is controlled on, such as a feature or a kind of data. Roles are given rights on resources through identity.resource_role.

@business-name: Resource
$$;

COMMENT ON COLUMN identity.resource.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.resource.code IS $$
The short, stable code other systems use to refer to the resource. Case-insensitive.

@business-name: Resource Code
@example: invoices
$$;

COMMENT ON COLUMN identity.resource.name IS $$
The resource's display name. Case-insensitive.

@business-name: Resource Name
@example: Invoices
$$;

COMMENT ON COLUMN identity.resource.description IS $$
What the resource is and what access to it allows.
$$;

COMMENT ON COLUMN identity.resource.is_deleted IS $$
Soft-delete flag. A deleted row is kept for history and ignored by normal queries; see deleted_utc.
$$;

COMMENT ON COLUMN identity.resource.is_active IS $$
Whether the row is in use. An inactive row is kept but not offered for new work.
$$;

COMMENT ON COLUMN identity.resource.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.resource.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.resource.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;
