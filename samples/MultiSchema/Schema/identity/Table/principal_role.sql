COMMENT ON TABLE identity.principal_role IS $$
Grants a role to a principal for a period of time. A principal holds a role while now falls between effective_from_utc and effective_to_utc.

@business-name: Principal Role
$$;

COMMENT ON COLUMN identity.principal_role.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.principal_role.principal_id IS $$
The principal that holds the role.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal_role.role_id IS $$
The role that is granted.

@see-also: identity.role.id
$$;

COMMENT ON COLUMN identity.principal_role.effective_from_utc IS $$
When the grant starts, in UTC. Defaults to the time the row is created.

@example: 2026-10-09 00:00:00
$$;

COMMENT ON COLUMN identity.principal_role.effective_to_utc IS $$
When the grant ends, in UTC. 9999-12-31 23:59:59 means the grant has no end.

@example: 9999-12-31 23:59:59
$$;

COMMENT ON COLUMN identity.principal_role.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal_role.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.principal_role.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal_role.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.principal_role.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal_role.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON CONSTRAINT principal_role_principal_id_role_id ON identity.principal_role IS $$
A principal is granted a given role only once; to change the period, change the existing row.
$$;
