COMMENT ON TABLE identity.resource_role IS $$
The rights a role has on a resource: one row per role and resource, with a flag for each of read, create, update, and delete.

@business-name: Resource Role
$$;

COMMENT ON COLUMN identity.resource_role.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.resource_role.resource_id IS $$
The resource the rights apply to.

@see-also: identity.resource.id
$$;

COMMENT ON COLUMN identity.resource_role.role_id IS $$
The role that has the rights.

@see-also: identity.role.id
$$;

COMMENT ON COLUMN identity.resource_role.is_read IS $$
Whether the role may read the resource.
$$;

COMMENT ON COLUMN identity.resource_role.is_create IS $$
Whether the role may create new items of the resource.
$$;

COMMENT ON COLUMN identity.resource_role.is_update IS $$
Whether the role may change existing items of the resource.
$$;

COMMENT ON COLUMN identity.resource_role.is_delete IS $$
Whether the role may delete items of the resource.
$$;

COMMENT ON COLUMN identity.resource_role.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource_role.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.resource_role.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource_role.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.resource_role.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.resource_role.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON CONSTRAINT resource_role_resource_id_role_id ON identity.resource_role IS $$
