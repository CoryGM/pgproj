COMMENT ON TABLE identity.user IS $$
A login identity. A user signs in through an identity provider and acts as a principal; users are not soft-deleted, only banned or merged into another user.

@business-name: User
$$;

COMMENT ON COLUMN identity.user.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.user.user_name IS $$
The name the user signs in with. Case-insensitive.

@business-name: User Name
@pii: true
@classification: confidential
@example: jane.doe
$$;

COMMENT ON COLUMN identity.user.idp_ids IS $$
The user's identifiers at external identity providers, as JSON. Null when the user has none.

@pii: true
@classification: confidential
$$;

COMMENT ON COLUMN identity.user.bans IS $$
The bans applied to the user, as JSON. Null when there are none; see is_banned.
$$;

COMMENT ON COLUMN identity.user.description IS $$
Free-text notes about the user.
$$;

COMMENT ON COLUMN identity.user.is_banned IS $$
Whether the user is currently banned from signing in; the details are in bans.
$$;

COMMENT ON COLUMN identity.user.merged_with_user_id IS $$
The user this one was merged into. Null for a user that has not been merged.

@see-also: identity.user.id
$$;

COMMENT ON COLUMN identity.user.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.user.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.user.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.user.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;
