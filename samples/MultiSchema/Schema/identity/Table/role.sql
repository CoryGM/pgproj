CREATE TABLE identity.role (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    code                        citext                          NOT NULL,
    name                        citext                          NOT NULL,
    description                 citext                          NULL,
    is_deleted                  boolean                         NOT NULL        DEFAULT false,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    created_principal_id		uuid							NOT NULL,
	created_utc					timestamp without time zone		NOT NULL 	    DEFAULT public.utc_now(), 
	updated_principal_id		uuid							NOT NULL,
	updated_utc					timestamp without time zone		NOT NULL	    DEFAULT public.utc_now(),
	deleted_principal_id		uuid							NULL,
	deleted_utc					timestamp without time zone		NULL
);

ALTER TABLE identity.role 
    ADD CONSTRAINT role_pkey PRIMARY KEY (id);

CREATE INDEX role_code ON identity.role (code);
CREATE INDEX role_created_principal_id ON identity.role (created_principal_id);
CREATE INDEX role_created_utc ON identity.role (created_utc);
CREATE INDEX role_updated_principal_id ON identity.role (updated_principal_id);
CREATE INDEX role_updated_utc ON identity.role (updated_utc);
CREATE INDEX role_deleted_principal_id ON identity.role (deleted_principal_id);
CREATE INDEX role_deleted_utc ON identity.role   (deleted_utc);

COMMENT ON TABLE identity.role IS $$
A named set of rights that can be granted to principals (identity.principal_role) and that holds rights on resources (identity.resource_role).

@business-name: Role
$$;

COMMENT ON COLUMN identity.role.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.role.code IS $$
The short, stable code other systems use to refer to the role. Case-insensitive.

@business-name: Role Code
@example: administrator
$$;

COMMENT ON COLUMN identity.role.name IS $$
The role's display name. Case-insensitive.

@business-name: Role Name
@example: Administrator
$$;

COMMENT ON COLUMN identity.role.description IS $$
What the role is for and who should hold it.
$$;

COMMENT ON COLUMN identity.role.is_deleted IS $$
Soft-delete flag. A deleted row is kept for history and ignored by normal queries; see deleted_utc.
$$;

COMMENT ON COLUMN identity.role.is_active IS $$
Whether the row is in use. An inactive row is kept but not offered for new work.
$$;

COMMENT ON COLUMN identity.role.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.role.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.role.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.role.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.role.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.role.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;
