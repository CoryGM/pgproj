COMMENT ON TABLE identity.principal IS $$
Someone or something that can act in the system: a person or a system actor. A principal is who is recorded in the audit columns of every table, and who is granted roles.

@business-name: Principal
$$;

COMMENT ON COLUMN identity.principal.id IS $$
The surrogate key, a time-ordered UUID (version 7) generated by the database.

@see-also: public.uuid_generate_v7
$$;

COMMENT ON COLUMN identity.principal.given_name IS $$
The principal's given (first) name.

@business-name: Given Name
@pii: true
@classification: confidential
@example: Jane
$$;

COMMENT ON COLUMN identity.principal.surname IS $$
The principal's family name. Null for a principal without one, such as a system actor.

@business-name: Surname
@pii: true
@classification: confidential
@example: Doe
$$;

COMMENT ON COLUMN identity.principal.display_name IS $$
The name shown for the principal in the user interface.

@business-name: Display Name
@pii: true
@classification: confidential
@example: Jane Doe
$$;

COMMENT ON COLUMN identity.principal.bans IS $$
The bans applied to the principal, as JSON. Null when there are none; see is_banned.
$$;

COMMENT ON COLUMN identity.principal.description IS $$
Free-text notes about the principal.
$$;

COMMENT ON COLUMN identity.principal.users IS $$
The users that belong to this principal, as JSON. Null when there are none.

@see-also: identity.user
$$;

COMMENT ON COLUMN identity.principal.is_system IS $$
Whether the principal is a built-in system actor rather than a person.
$$;

COMMENT ON COLUMN identity.principal.is_deleted IS $$
Soft-delete flag. A deleted row is kept for history and ignored by normal queries; see deleted_utc.
$$;

COMMENT ON COLUMN identity.principal.is_banned IS $$
Whether the principal is currently banned; the details are in bans.
$$;

COMMENT ON COLUMN identity.principal.is_active IS $$
Whether the row is in use. An inactive row is kept but not offered for new work.
$$;

COMMENT ON COLUMN identity.principal.merged_with_principal_id IS $$
The principal this one was merged into. Null for a principal that has not been merged.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal.created_principal_id IS $$
The principal that created the row.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal.created_utc IS $$
When the row was created, in UTC. Set by the database.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.principal.updated_principal_id IS $$
The principal that last changed the row. Equal to created_principal_id until the first change.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal.updated_utc IS $$
When the row was last changed, in UTC. Equal to created_utc until the first change.

@example: 2026-10-09 14:03:00
$$;

COMMENT ON COLUMN identity.principal.deleted_principal_id IS $$
The principal that soft-deleted the row. Null while the row is not deleted.

@see-also: identity.principal.id
$$;

COMMENT ON COLUMN identity.principal.deleted_utc IS $$
When the row was soft-deleted, in UTC. Null while the row is not deleted.

@example: 2026-10-09 14:03:00
$$;
