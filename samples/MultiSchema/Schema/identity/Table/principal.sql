CREATE TABLE identity.principal (
    id                          uuid                            NOT NULL        DEFAULT public.uuid_generate_v7(),
    given_name                  citext                          NOT NULL,
    surname                     citext                          NULL,
    display_name                citext                          NOT NULL,
    bans                        jsonb                           NULL,       
    description                 citext                          NULL,
    users                       jsonb                           NULL,
    is_system                   boolean                         NOT NULL        DEFAULT false,  
    is_deleted                  boolean                         NOT NULL        DEFAULT false,
    is_banned                   boolean                         NOT NULL        DEFAULT false,
    is_active                   boolean                         NOT NULL        DEFAULT true,
    merged_with_principal_id    uuid                            NULL,
    created_principal_id		uuid							NOT NULL,
	created_utc					timestamp without time zone		NOT NULL 	    DEFAULT public.utc_now(), 
	updated_principal_id		uuid							NOT NULL,
	updated_utc					timestamp without time zone		NOT NULL	    DEFAULT public.utc_now(),
	deleted_principal_id		uuid							NULL,
	deleted_utc					timestamp without time zone		NULL
);

